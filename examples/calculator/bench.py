@rule
def advance(phase):
    phase = phase + 1


@system
def ExerciseCalculator():  # noqa: N802
    phase: bits[64] = 0

    scenarios = scenario_rows()
    position = phase if phase < 237 else 236
    scenario = scenarios[position]
    key = scenario.key
    key_press = scenario.key_press
    dut = Calculator(key, key_press)

    expected_display = scenario.expected_display
    expected_op_pending = scenario.expected_op_pending

    @rule
    def check_and_advance():
        if phase < 237:
            assert dut.display == expected_display, "calculator: display"
            assert dut.op_pending == expected_op_pending, "calculator: op_pending"

        log("info", "calculator.display", dut.display)
        log("info", "calculator.op_pending", dut.op_pending)

    advance(phase)
