module tb;
  logic [12:0] a13,b13;
  logic [36:0] a37,b37;
  logic choose;
  wire [12:0] masked13,mixed13,zero13;
  wire [36:0] xor37,pick37;
  wire less,truth;
  pyc_root dut(.*);
  task row(input logic [12:0] a,b,input logic [36:0] x,y,input logic s,
           input logic [12:0] masked,input logic [36:0] xored,
           input logic [12:0] mixed,input logic [36:0] picked,
           input logic lt,t,input logic [12:0] z);
    a13=a;b13=b;a37=x;b37=y;choose=s;#1;
    if(!(masked13===masked && xor37===xored && mixed13===mixed && pick37===picked &&
         less===lt && truth===t && zero13===z))$fatal(1,"fixed four-state output oracle failed");
    $display("WORK %b %b %b %b %b %b %b",masked13,xor37,mixed13,pick37,less,truth,zero13);
  endtask
  initial begin
    // X selector, equal known branches
    row(13'b0000000000001,13'b0000000000001,37'b1000000000000000000000000000000000101,37'b1000000000000000000000000000000000101,1'bx,
        13'b0000000000001,37'b0000000000000000000000000000000000000,13'b1111111111111,37'b1000000000000000000000000000000000101,1'b0,1'b1,13'b0000000000000);
    // Z selector, branches differ only at bit 36
    row(13'b0000000000010,13'b0000000000001,37'b0000000000000000000000000000000000000,37'b1000000000000000000000000000000000000,1'bz,
        13'b0000000000000,37'b1000000000000000000000000000000000000,13'b1111111111110,37'bx000000000000000000000000000000000000,1'b0,1'b1,13'b0000000000000);
    // Narrow X/Z: AND zero dominates Z; OR one dominates Z
    row(13'b00000000001zx,13'b0000000000101,37'b0000000000000000000000000000000000000,37'b0000000000000000000000000000000000000,1'b1,
        13'b000000000010x,37'b0000000000000000000000000000000000000,13'b111111111111x,37'b0000000000000000000000000000000000000,1'bx,1'b1,13'b0000000000000);
    // High Z at bit 36, X at bit 35: selected input preserves both
    row(13'b0000000000000,13'b00000000010xz,37'bzx00000000000000000000000000100100011,37'b0000000000000000000000000000000000000,1'b0,
        13'b0000000000000,37'bxx00000000000000000000000000100100011,13'b11111111101xx,37'bzx00000000000000000000000000100100011,1'bx,1'b1,13'b0000000000000);
    // Z selector merges bit 1 disagreement while retaining bit 36
    row(13'b1010101010101,13'b0101010101010,37'b1000000000000000000000000000000000101,37'b1000000000000000000000000000000000111,1'bz,
        13'b0000000000000,37'b0000000000000000000000000000000000010,13'b1010101010101,37'b10000000000000000000000000000000001x1,1'b0,1'b1,13'b0000000000000);
    // Bitwise operations convert Z to X; controlling zero/one remain known
    row(13'bzzzzzzzzzzzzz,13'b0000000000000,37'b1111111111111111111111111111111111111,37'bz000000000000000000000000000100100011,1'b1,
        13'b0000000000000,37'bx111111111111111111111111111011011100,13'b1111111111111,37'bx000000000000000000000000000100100011,1'bx,1'b1,13'b0000000000000);
    $finish;
  end
endmodule
