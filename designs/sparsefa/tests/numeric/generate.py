"""Generate independent host-float oracle vectors, never DUT results."""
import math
import random
import struct
from pathlib import Path


def bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]

rng = random.Random(20516)
rows = []
for i in range(32):
    a = struct.unpack('<f', struct.pack('<f', rng.uniform(-8, 8)))[0]
    b = struct.unpack('<f', struct.pack('<f', rng.uniform(0.01, 8)))[0]
    x = -i / 2
    vals = {"a": bits(a), "b": bits(b), "x": bits(x), "add": bits(a+b), "mul": bits(a*b), "div": bits(a/b), "exp": bits(math.exp(x))}
    rows.append('        Case(' + ', '.join(f'{k}={v}' for k,v in vals.items()) + '),')
source = '''# ruff: noqa: F821, F823, F841, N802 -- compiler-owned hardware state and System names.
"""Independent seeded finite-profile numeric checks (generated by generate.py)."""
import pycircuit as ac
from fa2.fa2_numeric import fp_add, fp_mul, fp_div, fp_exp_neg, decode16, encode16

@ac.struct
class Case:
    a: ac.u32
    b: ac.u32
    x: ac.u32
    add: ac.u32
    mul: ac.u32
    div: ac.u32
    exp: ac.u32

def cases() -> ac.table[32, Case]:
    rows: ac.table[32, Case] = (
''' + '\n'.join(rows) + '''
    )
    return rows

@ac.rule
def advance(phase):
    phase = phase + 1

@ac.system
def NumericSystem():
    phase: ac.u5 = 0
    rows = cases()
    row = rows[phase]
    added = fp_add(row.a, row.b)
    multiplied = fp_mul(row.a, row.b)
    divided = fp_div(row.a, row.b)
    exponential = fp_exp_neg(row.x)
    half = encode16(row.a, 0)
    bfloat = encode16(row.a, 1)
    from_half = decode16(half, 0)
    from_bfloat = decode16(bfloat, 1)

    @ac.rule
    def check():
        assert (added & 2147483648) == (row.add & 2147483648), "add sign"
        assert (added & 2147483647) + 2 >= (row.add & 2147483647), "add lower"
        assert (added & 2147483647) <= (row.add & 2147483647) + 2, "add upper"
        assert (multiplied & 2147483648) == (row.mul & 2147483648), "mul sign"
        assert (multiplied & 2147483647) + 2 >= (row.mul & 2147483647), "mul lower"
        assert (multiplied & 2147483647) <= (row.mul & 2147483647) + 2, "mul upper"
        assert (divided & 2147483648) == (row.div & 2147483648), "div sign"
        assert (divided & 2147483647) + 2 >= (row.div & 2147483647), "div lower"
        assert (divided & 2147483647) <= (row.div & 2147483647) + 2, "div upper"
        assert exponential + 1024 >= row.exp, "exp lower"
        assert exponential <= row.exp + 1024, "exp upper"
        assert from_half == (row.a & 4294959104), "half normal truncation"
        assert from_bfloat == (row.a & 4294901760), "bfloat normal truncation"
        ac.log("info", "numeric", phase, added, multiplied, divided, exponential)
    check()
    advance(phase)
'''
Path(__file__).with_name('bench.py').write_text(source)
