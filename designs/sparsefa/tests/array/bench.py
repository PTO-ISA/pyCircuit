@ac.system
def ArraySystem():
    cycle: ac.u8 = 0
    completed: ac.u6 = 0
    array = Array16x16()
    data = schedule()
    command = data[cycle]
    operands = operand_words()
    left = vector(operands[command.left_id])
    right = vector(operands[command.right_id])

    @ac.rule
    def tick() -> None:
        if cycle == 235:
            assert completed == 25, "every expected array result completed"
            ac.log("info", "array_pass", completed)
        cycle = cycle + 1

    @ac.rule
    def drive() -> None:
        if command.op == 1:
            array.begin(
                ArrayBegin(
                    tag=command.tag, length=command.length, cell_mask=command.cell_mask
                )
            )
            ac.log(
                "info", "array_action", cycle, command.op, command.tag, command.index
            )
        elif command.op == 2:
            array.step(
                ArrayStep(
                    tag=command.tag,
                    index=command.index,
                    left=left,
                    right=right,
                    row_mask=command.row_mask,
                    col_mask=command.col_mask,
                )
            )
            ac.log(
                "info", "array_action", cycle, command.op, command.tag, command.index
            )
        elif command.op == 3:
            array.end(command.tag)
            ac.log(
                "info", "array_action", cycle, command.op, command.tag, command.index
            )
        elif command.op == 4:
            result = array.take()
            publish(result)
            completed = completed + 1
            ac.log("info", "array_action", cycle, command.op, result.tag, command.index)
        elif command.op == 5:
            array.abort(command.tag)
            ac.log(
                "info", "array_action", cycle, command.op, command.tag, command.index
            )

    tick()
    drive()
