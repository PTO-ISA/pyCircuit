def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Serial, resumable full validation of crawler-discovered RTL modules")
    parser.add_argument("--inventory", type=Path, default=DEFAULT_SCAN / "crawl" / "candidate_details.csv")
    parser.add_argument("--crawler-root", type=Path, default=DEFAULT_CRAWLER)
    parser.add_argument("--sources", type=Path, default=DEFAULT_SOURCES)
    parser.add_argument("--workdir", type=Path, default=DEFAULT_WORKDIR)
    parser.add_argument("--output", type=Path, default=REPO_ROOT / "build" / "runtime-full-validation")
    parser.add_argument("--liberty", type=Path, default=REPO_ROOT / "build" / "reference_libs" / "nangate45" / "NangateOpenCellLibrary_typical.lib")
    parser.add_argument("--no-liberty", action="store_true")
    parser.add_argument("--frontend", choices=["auto", "slang", "native"], default="auto")
    parser.add_argument("--max-modules", type=int, default=0, help="0 means all unique modules")
    parser.add_argument("--max-cases", type=int, default=0, help="0 means both sweep points for every module")
    parser.add_argument("--project-filter", action="append", default=[], help="only run candidates from this project (repeatable)")
    parser.add_argument("--module-filter", action="append", default=[], help="only run these module names (repeatable)")
    parser.add_argument("--build-timeout", type=int, default=180)
    parser.add_argument("--tool-timeout", type=int, default=180)
    parser.add_argument("--resume", action="store_true", default=True)
    parser.add_argument("--no-resume", action="store_false", dest="resume")
    args = parser.parse_args(argv)

    # All paths passed through WSL must be absolute.  In particular, a
    # relative ``--candidate-root`` would otherwise be resolved relative to
    # the pyCircuit crawler checkout rather than this Agentic Circuit repo.
    args.inventory = args.inventory.resolve()
    args.crawler_root = args.crawler_root.resolve()
    args.sources = args.sources.resolve()
    args.workdir = args.workdir.resolve()
    args.output = args.output.resolve()
    args.liberty = args.liberty.resolve()

    candidates = load_candidates(args.inventory)
    # Recover legacy Verilog-2001 port directions before wrappers and sweeps
    # are generated.  This fixes metadata-only lint failures without changing
    # the vendored RTL sources.
    for candidate in candidates:
        recover_legacy_port_metadata(candidate, args.workdir)
        repair_known_port_metadata(candidate)
    if args.project_filter:
        wanted = {str(item) for item in args.project_filter}
        candidates = [item for item in candidates if str(item.get("source_project", "")) in wanted]
    if args.module_filter:
        wanted = {str(item) for item in args.module_filter}
        candidates = [item for item in candidates if str(item.get("module", "")) in wanted]
    if args.max_modules:
        candidates = candidates[: max(0, args.max_modules)]
    full_inventory_run = not args.project_filter and not args.module_filter and not args.max_modules and not args.max_cases
    args.output.mkdir(parents=True, exist_ok=True)
    # A bounded/filtered invocation must not discard results from an earlier
    # full campaign.  Rehydrate cached case rows both from the previous report
    # and from per-case result.json files (the latter also recovers a report
    # interrupted before its final write).  New rows replace matching keys at
    # the end of the run; untouched candidates remain visible and auditable.
    cached_case_results: dict[str, dict[str, Any]] = {}
    previous_report = read_json(args.output / "report.json", {})
    if isinstance(previous_report, dict):
        for item in previous_report.get("case_results", []):
            if isinstance(item, dict):
                key = str(item.get("case_key") or "|".join(str(item.get(field, "")) for field in ("project", "module", "source_file", "config")))
                if key:
                    cached_case_results[key] = item
    for result_path in (args.output / "cases").glob("*/*/*/result.json"):
        item = read_json(result_path, {})
        if isinstance(item, dict):
            key = str(item.get("case_key") or "|".join(str(item.get(field, "")) for field in ("project", "module", "source_file", "config")))
            # The report is the authoritative cumulative snapshot once it has
            # been written.  Per-case files are only a recovery source for a
            # campaign interrupted before its final report write; allowing an
            # obsolete per-case file to overwrite the report resurrects sweep
            # rows that a later run intentionally removed (for example a type
            # parameter's old ``s1`` case).  Keep the first report value when
            # both sources contain the same key; the current invocation will
            # replace it explicitly as each candidate is recomputed.
            if key and key not in cached_case_results:
                cached_case_results[key] = item
    json_dump(args.output / "campaign.json", {
        "schema": "acir-runtime-full-validation-v0.1",
        "inventory": str(args.inventory),
        "crawler_root": str(args.crawler_root),
        "sources": str(args.sources),
        "workdir": str(args.workdir),
        "serial": True,
        "parser_token_prunes": {key: list(value) for key, value in PARSER_TOKEN_PRUNES.items()},
        "project_prune_includes": {key: list(value) for key, value in PROJECT_PRUNE_INCLUDES.items()},
        "project_prune_modules": {key: list(value) for key, value in PROJECT_PRUNE_MODULES.items()},
        "vortex_support_prunes": list(VORTEX_SUPPORT_PRUNES),
        "filters": {"projects": list(args.project_filter), "modules": list(args.module_filter)},
        "limits": {"build_timeout_s": args.build_timeout, "tool_timeout_s": args.tool_timeout},
    })

    liberty = None if args.no_liberty else args.liberty.resolve()
    if liberty and not liberty.exists():
        liberty = None
    frontend = args.frontend
    if frontend == "auto":
        frontend = "slang" if detect_slang(args.tool_timeout) else "native"

    vortex_support = prepare_vortex_support(args.output, args.workdir, args.tool_timeout)
    json_dump(args.output / "vortex-support.json", vortex_support)

    case_results: list[dict[str, Any]] = []
    candidate_results: list[dict[str, Any]] = []
    visited_candidate_keys: set[tuple[str, str, str]] = set()
    visited_candidate_names: set[tuple[str, str]] = set()
    candidate_root = args.output / "candidate-builds"
    sources_arg = wsl_path(args.sources)
    workdir_arg = wsl_path(args.workdir)
    for index, candidate in enumerate(candidates, start=1):
        project = str(candidate["source_project"])
        module = str(candidate["module"])
        visited_candidate_keys.add((project, module, str(candidate.get("file", ""))))
        visited_candidate_names.add((project, module))
        candidate_dir = candidate_root / safe(project) / safe(module)
        candidate_dir.mkdir(parents=True, exist_ok=True)
        manifest = candidate_dir / "manifest.json"
        # The lightweight scanner can index SystemVerilog interface names as
        # if they were modules (the PULP memory splitter exposes interfaces
        # named ``in``/``out``).  They are not standalone synthesizable tops.
        if module in {"in", "out", "input", "output"}:
            build_status = "BLOCKED_NON_MODULE"
            result = {
                "project": project, "module": module, "source_file": candidate.get("file", ""),
                "config": "none", "parameters": {}, "closure": build_status,
                "verilator_lint": "BLOCKED_NON_MODULE", "simulation": "BLOCKED_NON_MODULE",
                "simulation_kind": "none", "synthesis": "BLOCKED_NON_MODULE",
                "semantic_contract": "SEMANTIC_CONTRACT_MISSING", "interface": "none",
                "commit_sha": candidate.get("commit_sha", ""), "repo_url": candidate.get("repo_url", ""),
                "warnings": ["scanner indexed an interface declaration rather than a standalone module"],
            }
            candidate_results.append({"project": project, "module": module, "source_file": candidate.get("file", ""), "closure": build_status, "cases": 1, "case_keys": [], "parser_token_prunes": list(PARSER_TOKEN_PRUNES.get(project, ())), "project_prune_includes": list(PROJECT_PRUNE_INCLUDES.get(project, ())), "project_prune_modules": list(PROJECT_PRUNE_MODULES.get(project, ())), "support_prunes": list(VORTEX_SUPPORT_PRUNES if project == "vortex" else ())})
            case_results.append(result)
            print(f"[{index}/{len(candidates)}] {project}/{module} closure={build_status}", flush=True)
            continue
        manifest_snapshot = read_json(manifest, {})
        build_status = "PASS" if manifest_snapshot.get("closure_status") == "COMPLETE" else "NOT_RUN"
        # Older campaigns were generated from the v0.9.3 worktree.  A
        # resumed run must rebuild those candidates when the v0.4 materialized
        # source cache is selected; otherwise fixes to generated headers and
        # interface dependencies would be applied to a stale checkout.
        old_filelist = ""
        try:
            old_filelist = (candidate_dir / "candidate.f").read_text(encoding="utf-8", errors="replace")
        except OSError:
            pass
        if build_status == "PASS" and old_filelist and "v0.9.3" in old_filelist and "v0.9.3" not in str(args.workdir):
            build_status = "NOT_RUN"
        if build_status != "PASS" or not args.resume:
            build_cmd = [
                "cd", shlex.quote(wsl_path(args.crawler_root)), "&&", "python3", "build_candidate.py", shlex.quote(module),
                "--project", shlex.quote(project), "--sources", shlex.quote(sources_arg),
                "--workdir", shlex.quote(workdir_arg), "--candidate-root", shlex.quote(wsl_path(candidate_root)),
                "--top-file", shlex.quote(str(candidate.get("file", ""))),
            ]
            # UVM/assertion reporting packages are verification-only and are
            # deliberately outside an RTL runtime candidate's implementation
            # closure.  The maintained v0.14 class specs make the same
            # exclusion for PULP and OpenTitan; apply it here as well so the
            # generic campaign does not reject otherwise synthesizable tops.
            if project == "pulp_common_cells":
                build_cmd += ["--prune-package", "assert_rpt_pkg", "--prune-package", "uvm_pkg"]
            elif project == "opentitan":
                build_cmd += ["--prune-package", "uvm_pkg"]
            for token in PROJECT_PRUNE_INCLUDES.get(project, ()):
                build_cmd += ["--prune-include", token]
            for token in PROJECT_PRUNE_MODULES.get(project, ()):
                build_cmd += ["--prune-module", token]
            for token in PARSER_TOKEN_PRUNES.get(project, ()):
                build_cmd += ["--prune-module", token]
            if project == "vortex":
                for token in VORTEX_SUPPORT_PRUNES:
                    build_cmd += ["--prune-module", token]
            build = run_wsl(" ".join(build_cmd), args.build_timeout)
            (candidate_dir / "build_stdout.log").write_text(build.get("stdout", ""), encoding="utf-8")
            (candidate_dir / "build_stderr.log").write_text(build.get("stderr", ""), encoding="utf-8")
            manifest_status = read_json(manifest, {}).get("closure_status")
            # A successful build_candidate process is not sufficient: the
            # manifest must prove a complete dependency closure.  Vortex and
            # several vendor trees intentionally return exit code 0 while
            # retaining unresolved packages/macros; those cases are blocked
            # rather than being reported as validated RTL.
            if manifest_status == "COMPLETE" and build.get("status") == "PASS":
                build_status = "PASS"
            elif build.get("status") == "TIMEOUT":
                build_status = "TIMEOUT"
            else:
                build_status = "FAIL_CLOSURE"
        support_meta = {"status": "SKIP", "include_roots": [], "sources": []}
        if project == "vortex":
            support_meta = augment_vortex_filelist(candidate, candidate_dir, args.workdir, vortex_support)
            manifest_data = read_json(manifest, {})
            if build_status != "PASS" and support_meta.get("status") == "PASS" and vortex_unresolved_is_supported(manifest_data, vortex_support):
                build_status = "PASS"
                manifest_data["closure_status_original"] = manifest_data.get("closure_status")
                manifest_data["closure_status"] = "COMPLETE"
                manifest_data["support_resolved_includes"] = [
                    edge.get("dependency_name") for edge in manifest_data.get("unresolved_dependencies", [])
                    if edge.get("dependency_kind") == "include"
                ]
                manifest_data["support_include_roots"] = support_meta.get("include_roots", [])
                manifest_data["support_sources"] = support_meta.get("sources", [])
                json_dump(manifest, manifest_data)
        elif project == "openpiton":
            # OpenPiton keeps generated ``.v.pyv``/``.h.pyv`` sources in the
            # clone rather than checked-in ``.v``/``.h`` files.  Materialize
            # the fixed-profile templates and re-evaluate closure before the
            # candidate is classified as blocked.
            support_meta = augment_openpiton_filelist(candidate, candidate_dir, args.workdir)
            manifest_data = read_json(manifest, {})
            if build_status != "PASS" and support_meta.get("status") == "PASS":
                build_status = "PASS"
                manifest_data["closure_status_original"] = manifest_data.get("closure_status_original", manifest_data.get("closure_status"))
                manifest_data["closure_status"] = "COMPLETE"
                manifest_data["support_sources"] = support_meta.get("sources", [])
                manifest_data["support_headers"] = support_meta.get("headers", [])
                json_dump(manifest, manifest_data)
        elif project == "blackparrot":
            # Apply only source-verified profile overlays (currently the
            # scratchpad's zero-width accelerator-cache pin correction).
            support_meta = augment_blackparrot_filelist(candidate, candidate_dir, args.workdir)
        elif project == "cva6":
            support_meta = augment_cva6_filelist(candidate, candidate_dir, args.workdir)
        # Support augmentation appends real package/interface dependencies to
        # the crawler filelist.  Re-run the deterministic ordering pass after
        # augmentation as well; otherwise a newly added *_pkg.sv can remain
        # below its importing module and fail only in Verilator/Yosys.
        normalize_candidate_filelist(candidate_dir, project, args.workdir)
        print(f"[{index}/{len(candidates)}] {project}/{module} closure={build_status}", flush=True)
        candidate_case_results: list[dict[str, Any]] = []
        if build_status == "PASS" and (candidate_dir / "candidate.f").exists():
            for config_index, values in enumerate(choose_sweeps(candidate)):
                if args.max_cases and len(case_results) >= args.max_cases:
                    break
                label = f"s{config_index}"
                result = run_case(candidate, values, label=label, output=args.output, candidate_dir=candidate_dir, liberty=liberty, frontend=frontend, tool_timeout=args.tool_timeout, workdir=args.workdir)
                result["candidate_closure"] = build_status
                if support_meta.get("status") == "PASS":
                    result["support"] = support_meta
                candidate_case_results.append(result)
                case_results.append(result)
        else:
            result = {
                "project": project, "module": module, "source_file": candidate.get("file", ""),
                "config": "none", "parameters": {}, "closure": build_status,
                "verilator_lint": "BLOCKED_CLOSURE", "simulation": "BLOCKED_CLOSURE",
                "simulation_kind": "none", "synthesis": "BLOCKED_CLOSURE",
                "semantic_contract": "SEMANTIC_CONTRACT_MISSING", "interface": "none",
                "commit_sha": candidate.get("commit_sha", ""), "repo_url": candidate.get("repo_url", ""),
                "warnings": ["dependency closure did not complete"],
            }
            candidate_case_results.append(result)
            case_results.append(result)
            if support_meta.get("status") == "PASS":
                result["support"] = support_meta
        candidate_results.append({"project": project, "module": module, "source_file": candidate.get("file", ""), "closure": build_status, "cases": len(candidate_case_results), "case_keys": [item.get("case_key", "") for item in candidate_case_results], "parser_token_prunes": list(PARSER_TOKEN_PRUNES.get(project, ())), "project_prune_includes": list(PROJECT_PRUNE_INCLUDES.get(project, ())), "project_prune_modules": list(PROJECT_PRUNE_MODULES.get(project, ())), "support_prunes": list(VORTEX_SUPPORT_PRUNES if project == "vortex" else ())})

    # Merge rows not visited by a bounded invocation.  This keeps reports
    # cumulative while still replacing stale results that were actually
    # recomputed in the current pass.
    # A revisited candidate may now produce a different legal sweep set.  Do
    # not retain obsolete configurations (for example an old integer sweep
    # for a type-only CVA6Cfg parameter); preserve cache rows only for
    # candidates outside this invocation's prefix/filter.
    merged_cases = {} if full_inventory_run else {
        key: item for key, item in cached_case_results.items()
        if (
            str(item.get("project", "")),
            str(item.get("module", "")),
            str(item.get("source_file", "")),
        ) not in visited_candidate_keys
        # A bounded rerun must also replace rows for the same logical top when
        # the inventory's source-file spelling/commit changed between crawler
        # versions.  Otherwise obsolete configurations survive in the merged
        # report even though the current candidate summary has fewer cases.
        and (
            str(item.get("project", "")),
            str(item.get("module", "")),
        ) not in visited_candidate_names
    }
    for item in case_results:
        key = str(item.get("case_key") or "|".join(str(item.get(field, "")) for field in ("project", "module", "source_file", "config")))
        if key:
            merged_cases[key] = item
    case_results = sorted(merged_cases.values(), key=lambda item: (str(item.get("project", "")), str(item.get("module", "")), str(item.get("source_file", "")), str(item.get("config", ""))))
    # Candidate summaries do not have individual result files; preserve rows
    # from a previous report when this invocation intentionally visits only a
    # prefix of the inventory.
    merged_candidates: dict[tuple[str, str, str], dict[str, Any]] = {}
    if isinstance(previous_report, dict) and not full_inventory_run:
        for item in previous_report.get("candidate_results", []):
            if isinstance(item, dict):
                key = (str(item.get("project", "")), str(item.get("module", "")), str(item.get("source_file", "")))
                merged_candidates[key] = item
    for item in candidate_results:
        key = (str(item.get("project", "")), str(item.get("module", "")), str(item.get("source_file", "")))
        merged_candidates[key] = item
    candidate_results = sorted(merged_candidates.values(), key=lambda item: (str(item.get("project", "")), str(item.get("module", "")), str(item.get("source_file", ""))))

    summary = {
        # ``candidate_results`` may include cached rows when a filtered
        # invocation refreshes only a subset of a previous campaign.  Count
        # the merged report rather than the current filter so the summary
        # remains truthful and cumulative (a rerun of one failed module must
        # not make a 27-module report claim it contains one module).
        "modules": len(candidate_results),
        "cases": len(case_results),
        "closure_pass": sum(item.get("closure") == "PASS" or item.get("candidate_closure") == "PASS" for item in case_results),
        "lint_pass": sum(item.get("verilator_lint") == "PASS" for item in case_results),
        "simulation_pass": sum(item.get("simulation") == "PASS" for item in case_results),
        "synthesis_pass": sum(item.get("synthesis") == "PASS" for item in case_results),
        "synthesis_not_applicable": sum(item.get("synthesis") == "NOT_APPLICABLE_NON_SYNTH" for item in case_results),
        "non_module_entries": sum(item.get("synthesis") == "BLOCKED_NON_MODULE" for item in case_results),
        "mapped_area_measured": sum(item.get("synthesis") == "PASS" and item.get("mapped_area") is not None for item in case_results),
        "ppa_unavailable": sum(item.get("synthesis") == "PASS" and any("mapping skipped" in str(warning) for warning in (item.get("warnings") or [])) for item in case_results),
        "ppa_unobservable": sum(item.get("synthesis") == "PASS" and item.get("mapped_area") is None and not any("mapping skipped" in str(warning) for warning in (item.get("warnings") or [])) for item in case_results),
        "semantic_contract_missing": sum(item.get("semantic_contract") == "SEMANTIC_CONTRACT_MISSING" for item in case_results),
        "status_counts": dict(Counter(item.get("synthesis", "UNKNOWN") for item in case_results)),
        "power_measured": 0,
        "frontend": frontend,
        "liberty": str(liberty) if liberty else None,
    }
    report = {
        "schema": "acir-runtime-full-validation-v0.1",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "summary": summary,
        "candidate_results": candidate_results,
        "case_results": case_results,
    }
    json_dump(args.output / "report.json", report)
    write_csv(args.output / "results.csv", case_results)
    write_html(report, args.output / "report.html")
    print(json.dumps({"output": str(args.output), **summary}, ensure_ascii=False, sort_keys=True))
    return 0


