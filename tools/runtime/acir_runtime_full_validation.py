"""Run a bounded validation campaign for every crawler-discovered RTL module.

The v0.14 pyCircuit runner has semantic adapters for only a small number of
design classes.  This coordinator fills the remaining *structural* gap without
inventing functional contracts: every discovered top is built through the
dependency-closure path, wrapped as ``pyc_synth_top``, linted and simulated with
Verilator, synthesized with Yosys, and measured at two bounded parameter
points.  Modules with a known semantic class can be pointed at the existing
canonical property runner; all other modules are explicitly reported as
``SEMANTIC_CONTRACT_MISSING`` even when their structural smoke passes.

The campaign is deliberately serial and checkpointed.  It can be interrupted
and resumed safely, and each tool invocation has an independent timeout.
"""

