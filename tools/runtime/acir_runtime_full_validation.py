def normalize_port(port: Mapping[str, Any]) -> dict[str, Any]:
    """Recover packed/unpacked dimensions the v0.14 scanner stores in raw text."""
    item = dict(port)
    raw = str(item.get("raw", "")).strip().rstrip(",")
    match = re.match(r"^(input|output|inout)\s+(.+)$", raw, flags=re.I)
    if not match:
        item.setdefault("unpacked", "")
        return item
    direction, rest = match.groups()
    direction = direction.lower()
    packed = ""
    unpacked = ""
    type_name = "logic"
    # A leading range means an implicit logic packed vector (common in older
    # BaseJump declarations).  Otherwise consume the declared type first.
    # A net declaration may omit the explicit ``logic`` keyword and carry
    # more than one packed dimension, e.g. BaseJump's
    # ``output [o_els_p-1:0][i_els_p-1:0] grants_o``.  Consume the complete
    # run of leading dimensions; consuming only the first leaves the second
    # range in front of the name and makes recovery fall through to the
    # legacy scan, which then mislabels the port as an input.
    leading = re.match(r"^((?:\[[^\]]+\]\s*)+)(.*)$", rest)
    if leading:
        leading_dims, rest = leading.groups()
        packed = "".join(re.findall(r"\[[^\]]+\]", leading_dims))
        rest = rest.strip()
    else:
        # Legacy ANSI headers frequently omit an explicit net type
        # (``input foo`` / ``output bar``).  Treat the lone identifier as the
        # port name with an implicit logic type instead of consuming it as a
        # typedef name and losing the declaration entirely.
        implicit_name = re.match(r"^([A-Za-z_$][A-Za-z0-9_$]*)\s*$", rest)
        if implicit_name:
            name = implicit_name.group(1)
            item.update({"name": name, "direction": direction, "type": "logic", "width": "", "unpacked": ""})
            return item
        type_match = re.match(r"^([A-Za-z_$][A-Za-z0-9_$:]*)\s*(.*)$", rest)
        if type_match:
            type_name, rest = type_match.groups()
            # Builtin types put their range before the net name; typedefs in
            # the PULP style put an unpacked array range before the name.
            dim = re.match(r"^(\[[^\]]+\])\s*(.*)$", rest)
            if dim:
                candidate_dim, rest = dim.groups()
                if type_name.lower() in _BUILTIN_PORT_TYPES:
                    packed = candidate_dim
                else:
                    unpacked = candidate_dim
    name_match = re.match(r"^([A-Za-z_$][A-Za-z0-9_$]*)\s*(.*)$", rest)
    if not name_match:
        item.setdefault("unpacked", "")
        return item
    name, rest = name_match.groups()
    trailing = re.match(r"^(\[[^\]]+\])", rest.strip())
    if trailing:
        unpacked = trailing.group(1)
    item.update({"name": name, "direction": direction, "type": type_name, "width": packed, "unpacked": unpacked})
    return item


def recover_legacy_port_metadata(candidate: dict[str, Any], workdir: Path) -> None:
    """Recover ports from non-ANSI Verilog-2001 declarations.

    A sizeable part of OpenPiton, NVDLA and the OHWR LM32 tree uses the old
    ``module top (a, b); input [W-1:0] a; output b;`` form.  The crawler keeps
    the ordered names but (correctly) cannot infer their direction from the
    header alone, which used to produce invalid ``unknown logic`` wrappers.
    Read the checked-out source declaration and fill only the missing fields;
    this is metadata recovery, not a source rewrite or a guessed interface.
    """
    ports = candidate.get("ports", [])
    if not isinstance(ports, list) or not ports:
        return
    if not any(
        isinstance(port, dict)
        and (
            str(port.get("direction", "")).lower() not in {"input", "output", "inout"}
            or not str(port.get("type", "")).strip()
            or "`" in str(port.get("type", ""))
            or str(port.get("raw", "")).lstrip().startswith("`")
            or not str(port.get("width", "")).strip() and "[" in str(port.get("raw", ""))
        )
        for port in ports
    ):
        return
    source = workdir / "repos" / str(candidate.get("source_project", "")) / str(candidate.get("file", ""))
    if not source.exists():
        return
    try:
        text = source.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return
    # Comments frequently contain words such as ``input`` and semicolons;
    # remove them before scanning declaration statements.  Restrict the
    # search to this candidate's own module body.  Generated LM32 files pack
    # many profiles into one translation unit and a whole-file search can
    # otherwise recover a same-named signal from an earlier profile (for
    # example treating lm32_jtag_full_debug's output jtag_csr_write_data as
    # an input because a different module declares it as an input).
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\r\n]*", " ", text)
    module_name = str(candidate.get("module", "")).strip()
    if module_name:
        module_match = re.search(
            rf"\bmodule\s+{re.escape(module_name)}\b(?P<body>.*?\bendmodule\b)",
            text,
            flags=re.I | re.S,
        )
        if module_match:
            text = module_match.group("body")
    builtin = {"wire", "reg", "logic", "bit", "integer", "int", "signed", "unsigned"}
    declarations: list[tuple[str, str]] = [
        (match.group(1).lower(), match.group(2))
        for match in re.finditer(r"\b(input|output|inout)\b([^;]*);", text, flags=re.I | re.S)
    ]
    recovered = False
    for port in ports:
        if not isinstance(port, dict):
            continue
        name = str(port.get("name", "")).strip()
        if not name:
            continue
        # First normalize the candidate's raw header fragment itself.  The
        # crawler stores conditional ANSI lines verbatim (for example
        # ``ifndef NO_RTL_CSM`` followed by ``input foo``), which otherwise
        # leaks the preprocessor token into the recorded type and direction.
        raw = str(port.get("raw", ""))
        raw_clean = "\n".join(
            line for line in raw.splitlines()
            if not line.strip().startswith("`")
        ).strip().rstrip(",")
        normalized = normalize_port({"raw": raw_clean}) if raw_clean else {}
        if normalized.get("name") == name and normalized.get("direction") in {"input", "output", "inout"}:
            port["direction"] = normalized["direction"]
            port["type"] = normalized.get("type") or "logic"
            if normalized.get("width"):
                port["width"] = normalized["width"]
            if normalized.get("unpacked"):
                port["unpacked"] = normalized["unpacked"]
            recovered = True
            # ANSI declarations can be recovered completely from the raw
            # spelling above, including typed unpacked arrays such as
            # ``output addr_t [NumBanks-1:0] bank_addr_o``.  Do not fall
            # through to the legacy declaration scan in this case: that
            # scan deliberately looks for semicolon-terminated declarations
            # and would treat the whole ANSI port list as one ``input``
            # statement, incorrectly changing every later port's direction.
            if normalized.get("width") or normalized.get("unpacked") or "[" not in raw_clean:
                continue
        direction_known = str(port.get("direction", "")).lower() in {"input", "output", "inout"}
        type_known = bool(str(port.get("type", "")).strip())
        width_known = bool(str(port.get("width", "")).strip())
        # ANSI headers in legacy source often provide a valid direction but
        # the crawler leaves the net type/range empty.  Recover those fields
        # from the raw port spelling as well as from non-ANSI declarations.
        # Do not overwrite a complete record recovered on an earlier pass.
        if direction_known and type_known and (width_known or "[" not in str(port.get("raw", ""))):
            continue
        for direction, body in declarations:
            match = re.search(rf"(?<![A-Za-z0-9_$]){re.escape(name)}(?![A-Za-z0-9_$])", body)
            if not match:
                continue
            # A declaration may contain ``input [W-1:0] a, b``.  Carry the
            # type/range prefix from the first comma-separated item to later
            # names in that declaration.
            fragment_start = body.rfind(",", 0, match.start()) + 1
            fragment = body[fragment_start:match.start()]
            first_fragment = body.split(",", 1)[0]
            prefix = fragment if ("[" in fragment or re.search(r"\b(?:wire|reg|logic|bit|integer|int)\b", fragment, re.I)) else first_fragment
            ranges = re.findall(r"\[[^\]]+\]", prefix)
            type_match = re.search(r"\b(wire|reg|logic|bit|integer|int|signed|unsigned)\b", prefix, flags=re.I)
            type_name = type_match.group(1).lower() if type_match else "logic"
            port.update({"direction": direction, "type": type_name, "width": ranges[0] if ranges else "", "unpacked": ""})
            recovered = True
            break
        if direction_known and (not type_known or not width_known):
            # Normalize the candidate's own raw header line after removing
            # preprocessor guards such as ``ifndef NO_RTL_CSM``.  This is
            # needed for OpenPiton's ANSI ``lsu_nospu_wrap`` where there are
            # no separate ``input ...;`` declarations to scan.
            raw = str(port.get("raw", ""))
            raw_clean = "\n".join(
                line for line in raw.splitlines()
                if not line.strip().startswith("`")
            ).strip().rstrip(",")
            normalized = normalize_port({"raw": raw_clean}) if raw_clean else {}
            if normalized.get("direction") in {"input", "output", "inout"}:
                port["type"] = normalized.get("type") or "logic"
                if normalized.get("width"):
                    port["width"] = normalized["width"]
                if normalized.get("unpacked"):
                    port["unpacked"] = normalized["unpacked"]
                recovered = True
    if recovered:
        candidate["_legacy_ports_inferred"] = True


def recover_known_top_metadata(candidate: dict[str, Any]) -> None:
    """Fill declarations the line scanner cannot parse from known RTL forms."""
    key = (str(candidate.get("source_project", "")), str(candidate.get("module", "")))
    metadata = KNOWN_TOP_METADATA.get(key)
    if not metadata:
        return
    if not candidate.get("parameters"):
        candidate["parameters"] = [dict(item) for item in metadata["parameters"]]
    if not candidate.get("ports"):
        candidate["ports"] = [dict(item) for item in metadata["ports"]]


def repair_known_port_metadata(candidate: dict[str, Any]) -> None:
    """Apply small, source-verified corrections to crawler port records."""
    project = str(candidate.get("source_project", ""))
    module = str(candidate.get("module", ""))
    ports = candidate.get("ports", [])
    if not isinstance(ports, list):
        return
    if project == "ohwr_general_cores" and module in {
        "lm32_jtag_full_debug", "lm32_jtag_medium_debug", "lm32_jtag_medium_icache_debug",
    }:
        # The generated LM32 JTAG profile declares this signal as an output
        # register.  The legacy scanner occasionally inherits the direction
        # from the surrounding debug module and marks it input, which makes a
        # wrapper connection look like an assignment to an input net.
        for port in ports:
            if isinstance(port, dict) and str(port.get("name", "")) == "jtag_csr_write_enable":
                port["direction"] = "output"
    if project == "ohwr_general_cores" and module == "lm32_load_store_unit":
        # ``dflush`` belongs to the full generated CPU profile, not the
        # standalone load/store unit candidate.  Do not invent a pin that the
        # RTL top does not expose.
        candidate["ports"] = [
            port for port in ports
            if not (isinstance(port, dict) and str(port.get("name", "")) == "dflush")
        ]
        # The standalone crawler profile intentionally leaves the LM32
        # optional cache/IRAM defines unset (lm32_include.v selects the
        # Wishbone data path).  The source therefore removes these
        # conditional pins at preprocessing time even though the line parser
        # records both branches.  Drop the branch-only pins from the wrapper
        # metadata so Verilator does not report PINNOTFOUND against the real
        # module.  Enabling either feature later should use a dedicated fixed
        # profile and explicit defines instead of silently assuming widths.
        conditional = {
            "dcache_refill_request", "dcache_restart_request",
            "dcache_stall_request", "dcache_refilling",
            "iram_d_adr_o", "iram_d_dat_o", "iram_d_dat_i",
            "iram_d_sel_o", "iram_d_we_o", "iram_d_en_o",
            "iram_stall_request_x",
        }
        candidate["ports"] = [
            port for port in candidate["ports"]
            if not (isinstance(port, dict) and str(port.get("name", "")) in conditional)
        ]


def parameter_entries(candidate: Mapping[str, Any]) -> list[dict[str, Any]]:
    out = []
    for item in candidate.get("parameters", []):
        if not isinstance(item, dict):
            continue
        raw = str(item.get("raw", ""))
        name = str(item.get("name", "")).strip()
        if not name or re.search(r"\blocalparam\b", raw):
            continue
        # ``parameters_json`` is already the crawler's module-parameter
        # list.  In Verilog-2001/SystemVerilog headers the line parser often
        # stores continuation items without repeating the ``parameter``
        # keyword (for example ``#(width_p, harden_p=1)`` becomes
        # ``harden_p=1``).  Filtering on the raw spelling therefore drops
        # mandatory parameters such as BaseJump's ``width_p`` and causes
        # Verilator errors like "Parameter without default value".  Keep
        # every non-localparam entry and let the type/default logic below
        # decide how it can be overridden.
        out.append(item)
    return out


def is_type_parameter(item: Mapping[str, Any]) -> bool:
    return str(item.get("type", "")).strip().lower() == "type" or bool(
        re.search(r"\bparameter\s+type\b", str(item.get("raw", "")), flags=re.I)
    )


def is_symbolic_parameter(item: Mapping[str, Any]) -> bool:
    declared = str(item.get("type", "")).strip()
    default = str(item.get("default", "")).strip()
    return (
        is_type_parameter(item)
        or "::" in declared
        or declared.endswith("_e")
        or "string" in declared.lower()
        or declared.lower().startswith("`string")
        or (default.startswith('"') and default.endswith('"'))
    )


def _literal(value: str) -> int | None:
    value = value.strip()
    if re.fullmatch(r"[-+]?\d+", value):
        return int(value)
    # Common Verilog sized literals: 8'd4, 4'hf, 1'b0.
    match = re.fullmatch(r"\d+'([bodhBODH])([0-9a-fA-F_xXzZ]+)", value)
    if match:
        try:
            base = {"b": 2, "o": 8, "d": 10, "h": 16}[match.group(1).lower()]
            return int(match.group(2).replace("_", ""), base)
        except ValueError:
            return None
    return None


def heuristic_value(name: str, default: str = "") -> int:
    """Pick conservative, legal values for mandatory size parameters."""
    literal = _literal(default)
    if literal is not None:
        if literal == 0:
            low = name.lower()
            if any(token in low for token in ("width", "bits", "depth", "els", "entries", "num", "count", "ports", "banks", "lanes", "ways", "n_in", "n_out", "n_oup", "middle", "meet")):
                return 1
        return literal
    low = name.lower()
    if any(token in low for token in ("width", "bits", "xlen", "data_w", "addr_w")):
        return 8
    if any(token in low for token in ("depth", "size", "els", "entries", "num", "count", "ports", "banks", "lanes", "ways", "n_in", "n_out", "n_oup", "oup")):
        return 4
    if any(token in low for token in ("middle", "meet")):
        return 1
    if low in {"n", "m", "k", "n_p", "m_p"}:
        return 4
    if any(token in low for token in ("enable", "valid", "lock", "fair", "reset", "pass", "secure", "harden", "debug", "model")):
        return 0
    return 1


def parameter_values(candidate: Mapping[str, Any]) -> dict[str, int]:
    values: dict[str, int] = {}
    derived: list[dict[str, Any]] = []
    for item in parameter_entries(candidate):
        if is_symbolic_parameter(item):
            continue
        name = str(item["name"])
        default = str(item.get("default", "")).strip()
        # Keep explicit literals (including an intentional zero) as-is.  A
        # non-literal default is deferred so expressions such as
        # ``$clog2(NUM_BANKS)`` and ``DATA_WIDTH >> 3`` can be evaluated after
        # their source parameters have received conservative values.
        if _literal(default) is not None or not default:
            values[name] = heuristic_value(name, default)
        else:
            derived.append(item)

    # Resolve derived parameter defaults to a fixed point.  The previous
    # implementation populated a heuristic value first and then skipped every
    # item already present in ``values``, which left derived widths at 8 even
    # when the swept bank/depth parameters made the exact value available.
    for _ in range(max(1, len(derived))):
        changed = False
        for item in derived:
            name = str(item.get("name", "")).strip()
            value = eval_expr(str(item.get("default", "")), values)
            if value is not None and values.get(name) != value:
                values[name] = value
                changed = True
        if not changed:
            break
    for item in derived:
        name = str(item.get("name", "")).strip()
        if name not in values:
            values[name] = heuristic_value(name, str(item.get("default", "")))
    return values


def sweep_values(name: str, base: int) -> tuple[int, int]:
    low = name.lower()
    if any(token in low for token in ("max_val", "max_value", "limit")):
        # Required BaseJump parameters such as max_val_p have no default and
        # must stay strictly positive; (0, 1) would elaborate a [-1:0]
        # counter and is not a legal structural point.
        return (max(1, base), max(2, base))
    if any(token in low for token in ("width", "bits", "xlen", "data_w", "addr_w")):
        return (4, max(8, base))
    size_like = any(token in low for token in ("depth", "els", "entries", "num", "count", "ports", "banks", "lanes", "ways", "n_in", "n_out", "n_oup", "oup")) or low in {"n", "m", "k", "n_p", "m_p"}
    if size_like:
        # One is legal for many queue/fanout primitives, but zero produces an
        # invalid ``[-1:0]`` vector and prevents a meaningful structural run.
        if base <= 1:
            return (2, 4)
        return (2, max(4, base))
    if base in (0, 1):
        return (0, 1)
    return (max(1, base // 2), base)


def choose_sweeps(candidate: Mapping[str, Any]) -> list[dict[str, int]]:
    base = parameter_values(candidate)
    entries = parameter_entries(candidate)
    # A type/configuration-only parameter (for example CVA6Cfg) cannot be
    # swept as an integer.  Keep the RTL's fixed package default instead of
    # emitting illegal overrides such as ``.CVA6Cfg(0)``/``.CVA6Cfg(1)``.
    if entries and all(is_symbolic_parameter(item) for item in entries):
        return [{"__config_index": 0}]
    if str(candidate.get("source_project", "")) == "pulp_axi" and str(candidate.get("module", "")) in {
        "axi_burst_splitter", "axi_burst_splitter_gran", "axi_burst_splitter_gran_ax_chan", "axi_burst_splitter_gran_counters",
    }:
        # The RTL defaults intentionally use zero to require a system-level
        # configuration.  Standalone structural cases need at least one queue
        # entry and a non-zero AXI ID width to avoid [-1:0] declarations.
        configs: list[dict[str, int]] = []
        for idx, size in enumerate((2, 4)):
            item = dict(base)
            for name in ("MaxReadTxns", "MaxWriteTxns", "MaxTxns"):
                if any(str(param.get("name", "")) == name for param in entries):
                    item[name] = size
            for name in ("IdWidth", "AxiIdWidth"):
                if any(str(param.get("name", "")) == name for param in entries):
                    item[name] = 4
            for name in ("AddrWidth", "DataWidth", "UserWidth"):
                if any(str(param.get("name", "")) == name for param in entries) and item.get(name, 0) <= 1:
                    item[name] = {"AddrWidth": 32, "DataWidth": 32, "UserWidth": 1}[name]
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    if str(candidate.get("source_project", "")) == "pulp_common_cells" and str(candidate.get("module", "")) in {
        "cc_cdc_fifo_gray_clearable_dst", "cc_cdc_fifo_gray_clearable_src",
    }:
        configs: list[dict[str, int]] = []
        for idx, depth in enumerate((2, 4)):
            item = dict(base)
            item["LogDepth"] = depth
            # ClearOnAsyncReset=1 has a documented minimum of three stages.
            item["SyncStages"] = max(3, int(item.get("SyncStages", 3)))
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    if str(candidate.get("source_project", "")) == "basejump_stl" and str(candidate.get("module", "")) == "bsg_round_robin_arb":
        # ``inputs_p`` is a required BSG_INV_PARAM and the scanner cannot
        # recover its type/default.  The generic heuristic used zero/one,
        # which creates illegal ``[-1:0]`` request/tag vectors and Verilator
        # rejects the size-changing casts in the RTL.  Use the smallest two
        # legal arbiter sizes and keep the source-defined log2 relationship
        # explicit for each sweep point.
        configs = []
        for idx, inputs in enumerate((2, 4)):
            item = dict(base)
            item["inputs_p"] = inputs
            item["lg_inputs_p"] = max(1, math.ceil(math.log2(inputs)))
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    # Never select a type/string/enum parameter as the sweep dimension.  The
    # old fallback picked ``data_t`` for Common Cells stream/register tops
    # whenever a second numeric parameter did not contain a size keyword,
    # producing illegal overrides such as ``.data_t(0)``.  Symbolic
    # parameters are specialized only by the closed wrapper below; numeric
    # parameters remain the sole source of sweep values.
    numeric_entries = [item for item in entries if not is_symbolic_parameter(item)]
    primary = next((str(item["name"]) for item in numeric_entries if any(t in str(item["name"]).lower() for t in ("width", "depth", "els", "entries", "num", "count", "n", "m", "k"))), None)
    if not primary and numeric_entries:
        primary = str(numeric_entries[0]["name"])
    if not primary:
        return [{"__config_index": 0}]
    # Berkeley HardFloat's recoded format requires at least a 3-bit exponent;
    # a generic half-range sweep would otherwise create an invalid [-1:0]
    # selection in fNToRecFN.  Keep both points legal while still exercising a
    # materially different FP8 configuration.
    if str(candidate.get("module", "")) == "VX_tcu_bhf_fp8mul" and any(
        str(item.get("name", "")) == "IN_EXPW" for item in entries
    ):
        configs = []
        for idx, value in enumerate((4, 8)):
            item = dict(base)
            item["IN_EXPW"] = value
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    if str(candidate.get("module", "")) in {"VX_fma_unit", "VX_fma_unit_rtl"}:
        # Exercise the supported F32 and F64 datapaths with legal pipeline
        # latencies.  The RTL core's static contract requires seven cycles for
        # F32 and eight for F64 after the format-dependent align stage.
        configs = []
        for idx, (latency, man_bits, exp_bits) in enumerate(((7, 23, 8), (8, 52, 11))):
            item = dict(base)
            item.update({"LATENCY": latency, "MAN_BITS": man_bits, "EXP_BITS": exp_bits})
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    # VX_stream_arb's MAX_FANOUT=1 branch does not reduce the request count
    # in its recursive join, so a multi-input VX_stream_xbar elaborates into
    # an identically recursive hierarchy.  MAX_FANOUT=2 is the smallest
    # supported structural point that strictly decreases the recursive
    # request count for both sweep configurations while preserving the
    # module's intended fanout implementation.
    if str(candidate.get("module", "")) == "VX_stream_xbar" and any(
        str(item.get("name", "")) == "MAX_FANOUT" for item in entries
    ):
        small, large = sweep_values(primary, base.get(primary, 1))
        configs = []
        for idx, value in enumerate((small, large)):
            item = dict(base)
            item[primary] = value
            item["MAX_FANOUT"] = 2
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    # BaseJump's DPI-backed non-synth memory models require byte-granular data
    # widths.  A generic width sweep starting at 4 would trip the model's own
    # assertion before the smoke could exercise the actual RTL.
    if str(candidate.get("module", "")).startswith("bsg_nonsynth_mem_") and any(
        str(item.get("name", "")) == "width_p" for item in entries
    ):
        configs = []
        for idx, value in enumerate((8, 16)):
            item = dict(base)
            item["width_p"] = value
            refresh_dependent_values(candidate, item)
            item["__config_index"] = idx
            configs.append(item)
        return configs
    small, large = sweep_values(primary, base.get(primary, 1))
    configs: list[dict[str, int]] = []
    for idx, value in enumerate((small, large)):
        item = dict(base)
        item[primary] = value
        refresh_dependent_values(candidate, item)
        item["__config_index"] = idx
        configs.append(item)
    return configs


def refresh_dependent_values(candidate: Mapping[str, Any], values: dict[str, int]) -> None:
    """Re-evaluate derived parameter/localparam widths after a sweep override."""
    for _ in range(max(1, len(candidate.get("parameters", [])))):
        changed = False
        for item in candidate.get("parameters", []):
            if not isinstance(item, dict):
                continue
            name = str(item.get("name", "")).strip()
            raw = str(item.get("raw", ""))
            default = str(item.get("default", "")).strip()
            if not name or is_symbolic_parameter(item) or _literal(default) is not None:
                continue
            if "localparam" not in raw.lower() and "parameter" not in raw.lower():
                continue
            value = eval_expr(default, values)
            if value is not None and values.get(name) != value:
                values[name] = value
                changed = True
        if not changed:
            break


def eval_expr(expr: str, values: Mapping[str, int]) -> int | None:
    """Evaluate the small arithmetic subset used by crawler width metadata."""
    text = expr.strip()
    # Vortex/OpenPiton use UP(x) (or the backtick macro `UP(x)) for a
    # zero-safe vector width.  Treat it as max(1, x) during wrapper parameter
    # evaluation so a derived width does not fall back to the generic 8-bit
    # heuristic (which can create an out-of-range assignment in the RTL).
    text = re.sub(r"`?UP\s*\(", "up(", text, flags=re.I)
    if not text:
        return None
    text = re.sub(r"`(?:BSG_)?(?:SAFE_)?CLOG2\s*\(", "clog2(", text, flags=re.I)
    text = re.sub(r"`(?:BSG_)?LOG2UP\s*\(", "log2up(", text, flags=re.I)
    # PULP common_cells derives select/index widths through the package
    # helper ``cc_pkg::idx_width``.  It is the same zero-safe ceil(log2)
    # relation used by the crawler's other width expressions; strip the
    # package qualifier so standalone wrappers get the exact width instead of
    # falling back to the generic 8-bit heuristic.
    text = re.sub(r"(?:[A-Za-z_][A-Za-z0-9_]*::)?idx_width\s*\(", "log2up(", text, flags=re.I)
    text = re.sub(r"`BSG_MIN\s*\(", "min(", text, flags=re.I)
    text = re.sub(r"`BSG_MAX\s*\(", "max(", text, flags=re.I)
    text = re.sub(r"\$clog2\s*\(", "clog2(", text)
    text = text.replace("$bits", "bits")
    text = re.sub(r"\b\d+'[dD](\d+)\b", r"\1", text)
    text = re.sub(r"\b(?:unsigned|signed)\s*'\s*\(", "(", text, flags=re.I)
    # Convert a simple Verilog ternary to Python.
    ternary = re.fullmatch(r"(.+?)\?(.+?):(.+)", text)
    if ternary:
        cond, yes, no = ternary.groups()
        cv = eval_expr(cond, values)
        if cv is not None:
            return eval_expr(yes if cv else no, values)
    text = text.replace("&&", " and ").replace("||", " or ")
    text = re.sub(r"(?<![=!<>])!(?!=)", " not ", text)
    text = re.sub(r"\b(unsigned|integer|int|longint)\b", "", text, flags=re.I)
    text = re.sub(r"'([01xXzZ])", "0", text)
    names = set(re.findall(r"\b[A-Za-z_][A-Za-z0-9_]*\b", text))
    env: dict[str, Any] = {name: int(value) for name, value in values.items()}
    env["clog2"] = lambda x: max(0, math.ceil(math.log2(max(1, int(x)))))
    env["log2up"] = lambda x: max(1, math.ceil(math.log2(max(1, int(x)))))
    env["up"] = lambda x: max(1, int(x))
    env["bits"] = lambda x: max(1, int(x).bit_length())
    env["min"] = min
    env["max"] = max
    if any(name not in env and name not in {"clog2", "log2up", "bits", "up", "min", "max", "and", "or", "not"} for name in names):
        return None
    try:
        value = eval(text, {"__builtins__": {}}, env)
        return int(value) if isinstance(value, (int, float, bool)) else None
    except (ArithmeticError, SyntaxError, NameError, ValueError, TypeError):
        return None


def dimension_text(width: str, values: Mapping[str, int]) -> tuple[str, bool]:
    """Turn packed width expressions into numeric ranges for a wrapper."""
    if not width:
        return "", True
    ok = True

    def repl(match: re.Match[str]) -> str:
        nonlocal ok
        body = match.group(1)
        parts = body.split(":", 1)
        if len(parts) != 2:
            ok = False
            return "[7:0]"
        hi = eval_expr(parts[0], values)
        lo = eval_expr(parts[1], values)
        if hi is None or lo is None:
            ok = False
            return "[7:0]"
        return f"[{hi}:{lo}]"

    result = re.sub(r"\[([^\]]+)\]", repl, width)
    return result, ok


def unsupported_port_shape(candidate: Mapping[str, Any]) -> str:
    # VX_mem_axi_xbar is handled by a dedicated internal interface-array
    # wrapper below; do not reject it as a flat-port candidate before that
    # adapter has a chance to connect its modports legally.
    if str(candidate.get("module", "")) == "VX_mem_axi_xbar":
        return ""
    builtin_types = {"", "logic", "wire", "reg", "bit", "integer", "int", "byte", "shortint", "longint", "signed", "unsigned"}
    aliases = {
        str(item.get("name", ""))
        for item in candidate.get("parameters", [])
        if isinstance(item, dict) and is_type_parameter(item)
    }
    for port in candidate.get("ports", []):
        raw = str(port.get("raw", ""))
        name = str(port.get("name", ""))
        if str(port.get("direction", "")).lower() not in {"input", "output", "inout"}:
            return f"port direction unavailable ({name}); legacy declaration recovery required"
        # The v0.14 parser stores packed ranges in ``width``.  A bracket after
        # the name is an unpacked array; emitting a wrong packed declaration is
        # worse than recording an honest, reproducible blocker.
        tail = raw[raw.rfind(name) + len(name):] if name and name in raw else ""
        if str(port.get("type", "")).strip().lower() not in builtin_types and str(port.get("type", "")).strip() not in aliases:
            return f"non-builtin port type {port.get('type')} ({name})"
        if "interface" in raw.lower() or "modport" in raw.lower() or direction_is_inout(port):
            return f"interface port {name}"
    return ""


def direction_is_inout(port: Mapping[str, Any]) -> bool:
    return str(port.get("direction", "")).lower() == "inout"


def type_override(item: Mapping[str, Any], values: Mapping[str, int]) -> str:
    """Render a conservative SystemVerilog type-parameter override."""
    default = str(item.get("default", "")).strip()
    if not default:
        return "logic [7:0]"
    for name, value in sorted(values.items(), key=lambda pair: -len(pair[0])):
        default = re.sub(rf"\b{re.escape(name)}\b", str(int(value)), default)
    default = re.sub(r"`(?:BSG_)?(?:SAFE_)?CLOG2\s*\(([^()]*)\)", r"$clog2(\1)", default, flags=re.I)
    return default


def resolve_port_type(port: Mapping[str, Any], candidate: Mapping[str, Any], values: Mapping[str, int]) -> str:
    declared = str(port.get("type", "")).strip()
    if not declared or declared.lower() in _BUILTIN_PORT_TYPES:
        return declared or "logic"
    aliases = {
        str(item.get("name", "")): item
        for item in candidate.get("parameters", [])
        if isinstance(item, dict) and is_type_parameter(item)
    }
    item = aliases.get(declared)
    if item:
        return type_override(item, values)
    return "logic"


def typed_unpacked_port(port: Mapping[str, Any]) -> bool:
    """Return whether an unpacked port is declared through a non-builtin type."""
    if not str(port.get("unpacked", "")).strip():
        return False
    builtin = {"", "logic", "wire", "reg", "bit", "integer", "int", "byte", "shortint", "longint", "signed", "unsigned"}
    return str(port.get("type", "")).strip().lower() not in builtin


def port_declaration(
    port: Mapping[str, Any],
    candidate: Mapping[str, Any],
    values: Mapping[str, int],
    *,
    output: bool = False,
    native_array: bool = False,
) -> str:
    name = str(port.get("name", ""))
    direction = str(port.get("direction", "input")).lower()
    if direction not in {"input", "output", "inout"}:
        direction = "input"
    packed, _ = dimension_text(str(port.get("width", "")), values)
    unpacked, _ = dimension_text(str(port.get("unpacked", "")), values)
    type_name = resolve_port_type(port, candidate, values)
    # Verilator's parameterized SV frontend is more reliable when a generic
    # top exposes nested arrays as packed dimensions.  The native candidates
    # may spell the outer dimension as unpacked (``data_t [N] data``); folding
    # that dimension into the packed vector preserves total bit width while
    # allowing the wrapper to be linted and synthesized consistently.
    packed_dims = "".join(item for item in (packed,) if item)
    kind = "inout wire" if direction == "inout" else direction
    declaration = f"{kind} {type_name}"
    if packed_dims:
        declaration += f" {packed_dims}"
    declaration += f" {name}"
    if native_array and unpacked:
        declaration += f" {unpacked}"
    elif not native_array and unpacked:
        declaration = f"{kind} {type_name}{unpacked} {name}" if not packed else f"{kind} {type_name}{unpacked}{packed} {name}"
    return declaration


def unpacked_count(unpacked: str, values: Mapping[str, int]) -> int | None:
    text = unpacked.strip().strip("[]")
    parts = text.split(":", 1)
    if len(parts) == 1:
        value = eval_expr(parts[0], values)
        return value + 1 if value is not None and value >= 0 else None
    hi, lo = eval_expr(parts[0], values), eval_expr(parts[1], values)
    if hi is None or lo is None:
        return None
    return abs(hi - lo) + 1


def generate_wrapper(candidate: Mapping[str, Any], values: Mapping[str, int]) -> tuple[str, list[str]]:
    params = parameter_entries(candidate)
    lines = ["module pyc_synth_top ("]
    ports = candidate.get("ports", [])
    declarations: list[str] = []
    warnings: list[str] = []
    native_declarations: list[str] = []
    native_assignments: list[str] = []
    native_names: dict[str, str] = {}
    for port in ports:
        name = str(port.get("name", ""))
        direction = str(port.get("direction", "input")).lower()
        if not name:
            continue
        packed, ok = dimension_text(str(port.get("width", "")), values)
        if not ok:
            warnings.append(f"width inference fallback for {name}")
        typed_unpacked = typed_unpacked_port(port)
        # Verilator's type-parameter elaboration represents ports such as
        # ``data_t [N-1:0]`` as a flattened packed vector at the module
        # boundary.  Keep the public wrapper flat and connect it directly;
        # introducing a native unpacked temporary makes the connection illegal
        # (port is not an array, expression is an array).  Builtin unpacked
        # ports continue to use the native temporary + streaming adapter below.
        declarations.append("  " + port_declaration(port, candidate, values, native_array=False))
        unpacked = str(port.get("unpacked", ""))
        if unpacked and not typed_unpacked:
            count = unpacked_count(unpacked, values)
            if count is None:
                warnings.append(f"unpacked dimension could not be evaluated for {name}")
                continue
            native_name = f"__native_{name}"
            native_names[name] = native_name
            resolved_type = resolve_port_type(port, candidate, values)
            packed, _ = dimension_text(str(port.get("width", "")), values)
            unpacked_eval, _ = dimension_text(unpacked, values)
            # Preserve the native unpacked shape on the temporary.  The public
            # wrapper intentionally exposes a flat packed port, so connect the
            # two with a streaming assignment.  Declaring the temporary as a
            # packed aggregate (the old implementation) is rejected by
            # Verilator when the DUT port is a true unpacked array.
            native_decl_type = " ".join(part for part in (resolved_type, packed, native_name) if part)
            native_declarations.append(f"  {native_decl_type} {unpacked_eval};")
            if direction == "input":
                native_assignments.append(f"  assign {native_name} = {{>>{{{name}}}}};")
            elif direction == "output":
                native_assignments.append(f"  assign {name} = {{>>{{{native_name}}}}};")
    lines.append(",\n".join(declarations))
    lines.append(");")
    if params:
        lines[0] = "module pyc_synth_top ("
    lines.append("")
    if params:
        lines.append("  // Parameter values are fixed per sweep case; the wrapper itself is stable.")
    if native_declarations:
        lines.extend(native_declarations)
        lines.extend(native_assignments)
    lines.append(f"  {candidate['module']} #(") if params else lines.append(f"  {candidate['module']} dut (")
    if params:
        assignments = []
        for item in params:
            name = str(item["name"])
            # Keep a declared type parameter's native default whenever one is
            # present.  Overriding a type such as ``data_t`` with an equivalent
            # textual type can change unpacked-array semantics in older
            # Verilator frontends; the default already tracks DataWidth.
            if is_type_parameter(item) and str(item.get("default", "")).strip():
                continue
            if is_symbolic_parameter(item):
                value = type_override(item, values)
                if str(candidate.get("source_project", "")) == "blackparrot" and name == "bp_params_p" and value.startswith("e_bp_"):
                    # The enum is declared in bp_common_pkg; an unqualified
                    # mnemonic in the generated top is parsed as an implicit
                    # (non-constant) signal by Verilator and cannot be used
                    # as a parameter value.
                    value = f"bp_common_pkg::{value}"
            else:
                value = str(int(values.get(name, heuristic_value(name, str(item.get("default", ""))))))
            assignments.append(f"    .{name}({value})")
        lines.append(",\n".join(assignments))
        lines.append("  ) dut (")
    connections = []
    for port in ports:
        name = str(port.get("name", ""))
        if name:
            connections.append(f"    .{name}({native_names.get(name, name)})")
    lines.append(",\n".join(connections))
    lines += ["  );", "endmodule", ""]
    return "\n".join(lines), warnings


def generate_tb(candidate: Mapping[str, Any], values: Mapping[str, int]) -> str:
    # VX_mem_axi_xbar is adapted as a closed, interface-only structural top
    # by generate_vortex_interface_wrapper().  It intentionally has no
    # public scalar ports, so the generic port-driven testbench must not try
    # to reconnect the crawler's interface metadata (clk/reset/s/m) to
    # pyc_synth_top.  A minimal bounded smoke is sufficient here: the
    # interface-array construction and DUT elaboration are exercised by the
    # wrapper, while no protocol-level contract is claimed by this campaign.
    if candidate.get("_closed_wrapper") or str(candidate.get("module", "")) == "VX_mem_axi_xbar":
        return """`timescale 1ns/1ps
module tb;
  pyc_synth_top dut ();
  initial begin
    #20;
    $display("PYC_GENERIC_SMOKE_PASS");
    $finish;
  end
endmodule
"""
    ports = candidate.get("ports", [])
    declarations: list[str] = []
    connections: list[str] = []
    inputs: list[str] = []
    clocks: list[str] = []
    resets: list[str] = []
    for port in ports:
        name = str(port.get("name", ""))
        direction = str(port.get("direction", "input")).lower()
        if not name:
            continue
        packed, _ = dimension_text(str(port.get("width", "")), values)
        unpacked, _ = dimension_text(str(port.get("unpacked", "")), values)
        resolved_type = resolve_port_type(port, candidate, values)
        typed_unpacked = typed_unpacked_port(port)
        packed_dims = "".join(item for item in (packed,) if item)
        tb_type = resolved_type if direction == "output" else "logic"
        declaration = f"  {tb_type} {packed_dims} {name}"
        # Typed unpacked arrays are flattened in the wrapper just like the
        # corresponding DUT port.  Builtin arrays use the same folded packed
        # representation as generate_wrapper().
        if direction != "output":
            declaration += " = '0"
        declarations.append(declaration + ";")
        if direction != "output":
            inputs.append(name)
            low = name.lower()
            if re.search(r"(^|_)(clk|clock)(_|$)", low) or low in {"clk", "clock"}:
                clocks.append(name)
            if low in {"rst_ni", "reset_ni", "rst_n", "reset_n"} or low.endswith("_rst_ni"):
                resets.append(name)
            elif low in {"rst_i", "reset_i", "rst", "reset"} or low.endswith("_reset_i"):
                resets.append(name)
        connections.append(f"    .{name}({name})")
    lines = ["`timescale 1ns/1ps", "module tb;", *declarations]
    for clock in clocks:
        lines.append(f"  always #5 {clock} = ~{clock};")
    lines.append("  pyc_synth_top dut (")
    lines.append(",\n".join(connections))
    lines += ["  );", "  initial begin"]
    for name in inputs:
        if name not in clocks:
            lines.append(f"    {name} = '0;")
    for name in resets:
        lines.append(f"    {name} = 1'b0;")
    lines.append("    #2;")
    for name in resets:
        # A suffix `_n` is active-low; ordinary reset names are active-high.
        if name.lower().endswith("_n") or name.lower().endswith("_ni"):
            lines.append(f"    {name} = 1'b1;")
        else:
            lines.append(f"    {name} = 1'b0;")
    # Keep stimulus quiescent for a structural smoke.  Driving every input to
    # one can intentionally trip RTL parameter assertions (for example a
    # memory bank's illegal strobe combination) and would turn an elaboration
    # check into an accidental functional test.  Semantic adapters own those
    # meaningful non-zero vectors.
    lines += ["    #20;", "    $display(\"PYC_GENERIC_SMOKE_PASS\");", "    $finish;", "  end", "endmodule", ""]
    return "\n".join(lines)


