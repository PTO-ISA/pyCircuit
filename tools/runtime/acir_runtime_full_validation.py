def safe(value: Any) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", str(value)).strip("_") or "unknown"


def wsl_path(path: Path | str) -> str:
    raw = str(path)
    # ``candidate.f`` files produced by the crawler may contain an already
    # converted WSL path (``/mnt/e/...``).  Keep it intact; blindly treating
    # it as a Windows relative path turns it into ``/mnt/e/mnt/e/...`` and
    # makes Yosys unable to open otherwise valid sources/includes.
    if re.match(r"^/mnt/[A-Za-z]/", raw):
        return raw.replace("\\", "/")
    match = re.match(r"^([A-Za-z]):[\\/](.*)$", raw)
    if match:
        # The Windows form can arise when pathlib joins a WSL absolute entry
        # from a filelist (for example ``E:\\mnt\\e\\...``).  Normalize it
        # back to the intended mount instead of nesting the mount again.
        rest = match.group(2).replace("\\", "/")
        drive = match.group(1).lower()
        if rest.lower().startswith(f"mnt/{drive}/"):
            return f"/mnt/{drive}/" + rest[len(f"mnt/{drive}/"):]
        return "/mnt/" + drive + "/" + rest
    return raw.replace("\\", "/")


def json_dump(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def read_json(path: Path, default: Any = None) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return default


def run_wsl(command: str, timeout: int) -> dict[str, Any]:
    """Run one isolated WSL command with the pinned OSS-CAD PATH."""
    shell = f"export PATH={WSL_PATH}; {command}"
    started = time.monotonic()
    # ``subprocess.run(..., timeout=...)`` only kills the Windows launcher.
    # The bash/tool descendants kept running inside the WSL VM, which made a
    # timed-out campaign continue consuming CPU and memory and could leave a
    # subsequent batch apparently hung.  Keep the launcher handle so the
    # entire process tree can be reaped on timeout.  This remains a no-op for
    # non-Windows callers, where the process group is terminated below.
    popen_kwargs: dict[str, Any] = {
        "text": True,
        "stdout": subprocess.PIPE,
        "stderr": subprocess.PIPE,
    }
    if os.name == "nt":
        # CREATE_NEW_PROCESS_GROUP gives taskkill /T an isolated root and
        # avoids accidentally touching a user-owned wsl.exe process.
        popen_kwargs["creationflags"] = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)
    else:
        popen_kwargs["start_new_session"] = True
    proc: subprocess.Popen[str] | None = None
    try:
        proc = subprocess.Popen(
            ["wsl.exe", "--", "/bin/bash", "-lc", shell],
            **popen_kwargs,
        )
        stdout, stderr = proc.communicate(timeout=max(1, timeout))
        return {
            "status": "PASS" if proc.returncode == 0 else "FAIL",
            "returncode": proc.returncode,
            "elapsed_s": round(time.monotonic() - started, 3),
            "stdout": (stdout or "")[-16000:],
            "stderr": (stderr or "")[-16000:],
            "command": command,
        }
    except subprocess.TimeoutExpired as exc:
        # Kill the Windows launcher and all descendants.  ``wsl.exe`` does
        # not reliably forward CTRL_BREAK to the Linux process tree, whereas
        # taskkill /T is deterministic for this process group.  Fall back to
        # ``kill`` for non-Windows environments and always drain the pipes so
        # the parent cannot remain blocked on a full capture buffer.
        if proc is not None:
            if os.name == "nt":
                try:
                    subprocess.run(
                        ["taskkill", "/PID", str(proc.pid), "/T", "/F"],
                        stdout=subprocess.DEVNULL,
                        stderr=subprocess.DEVNULL,
                        timeout=5,
                        check=False,
                    )
                except (OSError, subprocess.TimeoutExpired):
                    pass
            else:
                try:
                    import os as _os
                    import signal as _signal
                    _os.killpg(proc.pid, _signal.SIGKILL)
                except (OSError, ProcessLookupError):
                    pass
            try:
                stdout, stderr = proc.communicate(timeout=5)
            except subprocess.TimeoutExpired:
                proc.kill()
                stdout, stderr = proc.communicate()
        else:
            stdout, stderr = "", ""
        return {
            "status": "TIMEOUT",
            "returncode": proc.returncode if proc is not None else None,
            "elapsed_s": round(time.monotonic() - started, 3),
            "stdout": (stdout or exc.stdout or "")[-16000:],
            "stderr": (stderr or exc.stderr or "")[-16000:],
            "command": command,
        }
    except OSError as exc:
        return {"status": "ERROR", "returncode": None, "elapsed_s": round(time.monotonic() - started, 3), "error": str(exc), "command": command}


def prepare_vortex_support(output: Path, workdir: Path, timeout: int) -> dict[str, Any]:
    """Generate Vortex build-tree headers used by the standalone RTL tops.

    Vortex's normal Makefiles create ``VX_config.vh`` and ``VX_types.vh`` in a
    build directory; they are intentionally absent from the source checkout.
    Reproduce that supported configuration here without modifying the external
    checkout.  The optional HardFloat submodule is consumed if it is present;
    the caller keeps TCU candidates blocked when it is not.
    """
    support = output / "generated" / "vortex"
    config = support / "VX_config.vh"
    types = support / "VX_types.vh"
    support.mkdir(parents=True, exist_ok=True)
    repo = workdir / "repos" / "vortex"
    if not repo.exists():
        return {"status": "MISSING_REPOSITORY", "path": str(support)}
    if not (config.exists() and types.exists()):
        commands = [
            "cd " + shlex.quote(wsl_path(repo)) + " && python3 ci/gen_config.py"
            " --config VX_config.toml --cflags '-DSYNTHESIS -DVX_CFG_XLEN=32'"
            " --format verilog --output " + shlex.quote(wsl_path(config)) + " --resolved",
            "cd " + shlex.quote(wsl_path(repo)) + " && python3 ci/gen_config.py"
            " --config VX_types.toml --cflags=-DVX_CFG_XLEN=32"
            " --format verilog --output " + shlex.quote(wsl_path(types)) + " --resolved",
        ]
        logs = []
        for command in commands:
            result = run_wsl(command, timeout)
            logs.append(result)
            if result.get("status") != "PASS":
                (support / "generation.log").write_text(json.dumps(logs, indent=2, ensure_ascii=False), encoding="utf-8")
                return {"status": "GENERATION_FAILED", "path": str(support), "logs": logs}
    return {
        "status": "PASS" if config.exists() and types.exists() else "INCOMPLETE",
        "path": str(support),
        "config": str(config),
        "types": str(types),
        "hardfloat": str(repo / "third_party" / "hardfloat" / "source"),
    }


def augment_vortex_filelist(candidate: Mapping[str, Any], candidate_dir: Path, workdir: Path, support: Mapping[str, Any]) -> dict[str, Any]:
    """Add generated/vendor support files to a Vortex candidate filelist."""
    filelist = candidate_dir / "candidate.f"
    if not filelist.exists() or support.get("status") != "PASS":
        return {"status": "SKIP", "include_roots": [], "sources": []}
    repo = workdir / "repos" / "vortex"
    include_dirs = [Path(str(support["path"])), repo / "hw" / "dpi", repo / "hw" / "rtl" / "tcu" / "bhf"]
    hardfloat = repo / "third_party" / "hardfloat" / "source"
    if hardfloat.exists():
        include_dirs.extend([hardfloat, hardfloat / "RISCV"])

    # These are all portable support paths.  The RAM model is only needed by
    # stream wrappers when a synthesis configuration selects the ASIC branch;
    # including it is harmless for the generic branch and makes the closure
    # self-contained if a future profile enables ASIC.
    extra_sources: list[Path] = [repo / "hw" / "syn" / "libs" / "no_mem" / "VX_dp_ram_asic.v"]
    # SystemVerilog interfaces are declarations, not module instances, so a
    # line-based closure pass does not add their source files.  Recover only
    # interfaces/packages referenced by this candidate's actual closure;
    # compiling every Vortex interface for every top would inflate memory and
    # introduce unrelated package requirements.
    manifest = read_json(candidate_dir / "manifest.json", {})
    referenced_text: list[str] = []
    rel_files: list[str] = []
    if isinstance(manifest, dict):
        rel_files.extend(str(item) for item in manifest.get("module_files", []) if str(item))
        rel_files.extend(str(item) for item in manifest.get("package_files", []) if str(item))
    rel_files.append(str(candidate.get("file", "")))
    for rel in dict.fromkeys(rel_files):
        path = repo / rel
        if path.exists():
            try:
                referenced_text.append(path.read_text(encoding="utf-8", errors="replace"))
            except OSError:
                pass
    ref_blob = "\n".join(referenced_text)
    iface_names = set(re.findall(r"\b(VX_[A-Za-z0-9_]+_if)\b", ref_blob))
    for path in sorted(repo.rglob("*_if.sv")):
        if path.stem in iface_names:
            extra_sources.append(path)
            include_dirs.append(path.parent)
    pkg_names = set(re.findall(r"\b(?:import|::)\s*(VX_[A-Za-z0-9_]+_pkg)\b", ref_blob))
    for path in sorted(repo.rglob("*.sv")):
        if path.stem in pkg_names and path not in extra_sources:
            extra_sources.append(path)
            include_dirs.append(path.parent)
    # The crawler's line-based dependency pass does not treat an interface
    # declaration used through a modport as a module edge.  VX_cp_dma and the
    # AXI crossbar therefore need the shared interface source supplied
    # explicitly; otherwise Verilator reports a missing VX_mem_axi_if even
    # though the repository contains the supported definition.
    if str(candidate.get("module", "")) in {"VX_cp_dma", "VX_mem_axi_xbar"}:
        extra_sources.append(repo / "hw" / "rtl" / "mem" / "VX_mem_axi_if.sv")
    if str(candidate.get("module", "")) == "VX_cp_axil_regfile":
        extra_sources.append(repo / "hw" / "rtl" / "cp" / "VX_cp_axil_s_if.sv")
    if str(candidate.get("module", "")) == "VX_stream_xbar":
        # VX_stream_xbar's collision counter is implemented with the shared
        # VX_popcount primitive.  The line-based crawler can miss this edge
        # because the reference is below a macro-generated helper, so make
        # the dependency explicit in the standalone runtime filelist.
        extra_sources.append(repo / "hw" / "rtl" / "libs" / "VX_popcount.sv")
    if str(candidate.get("module", "")) == "VX_tcu_sp_mux":
        # Sparse TCU units are guarded by this feature macro and import both
        # GPU/TCU packages.  The fixed profile enables the unit explicitly.
        extra_sources.extend([
            repo / "hw" / "rtl" / "VX_gpu_pkg.sv",
            repo / "hw" / "rtl" / "tcu" / "VX_tcu_pkg.sv",
        ])
    # The crawler's line-oriented scanner does not follow package imports
    # hidden behind interface parameters or macro-generated helper instances.
    # Keep these real Vortex sources in the standalone closure for the
    # interface-heavy CPU/GPU blocks below.  They are not substitutes: they
    # are the checked-out RTL units required by the DUT itself.
    module_name = str(candidate.get("module", ""))
    vortex_extra_by_module = {
        "VX_lsu_unit": [
            repo / "hw" / "rtl" / "core" / "VX_lane_dispatch.sv",
            repo / "hw" / "rtl" / "core" / "VX_lsu_slice.sv",
            repo / "hw" / "rtl" / "core" / "VX_lane_gather.sv",
            repo / "hw" / "rtl" / "core" / "VX_lsu_agu.sv",
            repo / "hw" / "rtl" / "libs" / "VX_stream_arb.sv",
        ],
        "VX_lsu_slice": [
            repo / "hw" / "rtl" / "core" / "VX_lsu_agu.sv",
            repo / "hw" / "rtl" / "libs" / "VX_stream_arb.sv",
        ],
        "VX_ptw": [
            repo / "hw" / "rtl" / "vm" / "VX_tlb_pkg.sv",
            repo / "hw" / "rtl" / "vm" / "VX_ptw_walker.sv",
            repo / "hw" / "rtl" / "vm" / "VX_ptw_cache.sv",
            repo / "hw" / "rtl" / "libs" / "VX_bits_insert.sv",
            repo / "hw" / "rtl" / "libs" / "VX_bits_remove.sv",
            repo / "hw" / "rtl" / "libs" / "VX_stream_switch.sv",
            repo / "hw" / "rtl" / "mem" / "VX_mem_bus_arb.sv",
        ],
        "VX_ptw_walker": [repo / "hw" / "rtl" / "vm" / "VX_tlb_pkg.sv"],
        "VX_tlb_bus_arb": [
            repo / "hw" / "rtl" / "VX_gpu_pkg.sv",
            repo / "hw" / "rtl" / "vm" / "VX_tlb_pkg.sv",
            repo / "hw" / "rtl" / "vm" / "VX_tlb_bus_if.sv",
        ],
    }
    extra_sources.extend(vortex_extra_by_module.get(module_name, []))
    if module_name == "VX_lsu_unit":
        # VX_lsu_agu and VX_stream_arb instantiate these library primitives
        # through macro-generated branches that the line-based crawler does
        # not see.  They are real Vortex sources required by the selected
        # fixed profile, not behavioral stand-ins.
        extra_sources.extend([
            repo / "hw" / "rtl" / "libs" / "VX_generic_arbiter.sv",
            repo / "hw" / "rtl" / "libs" / "VX_priority_arbiter.sv",
            repo / "hw" / "rtl" / "libs" / "VX_priority_encoder.sv",
            repo / "hw" / "rtl" / "libs" / "VX_csa_32.sv",
        ])
    if module_name == "VX_csr_unit":
        # Yosys/slang rejects the upstream CSR_READ_64 macro when its source
        # operand is a field selected through an interface (hierarchical
        # references are not legal in $bits).  The generated Vortex profile
        # uses PERF_CTR_BITS=44 (the architectural counter is wider than the
        # 32-bit datapath, but is not a full 64 bits).  Materialise a
        # source-verified overlay which preserves that width: the low CSR
        # word is the original low 32 bits and the high word is zero-extended
        # from bits [43:32].  This avoids the old hard-coded [63:32] range
        # error while leaving the upstream checkout untouched.
        src = repo / "hw" / "rtl" / "core" / "VX_csr_data.sv"
        if src.exists():
            try:
                text = src.read_text(encoding="utf-8", errors="replace")
                # The fixed VX_CFG_XLEN=32 profile derives
                # VX_CSR_COUNTER_WIDTH/PERF_CTR_BITS=44.  Keep the overlay
                # explicit and width-safe rather than selecting a range past
                # the actual interface field (slang treats that as an error).
                text = text.replace("src[$bits(src)-1:32]", "{{20{1'b0}}, src[43:32]}")
                overlay = candidate_dir.parent.parent.parent / "generated" / "vortex" / "VX_csr_data_yosys.sv"
                overlay.parent.mkdir(parents=True, exist_ok=True)
                overlay.write_text(text, encoding="utf-8")
                # The original file is present in the crawler closure; swap
                # only this path for the generated, semantically equivalent
                # profile so duplicate VX_csr_data modules are not parsed.
                extra_sources.append(overlay)
                original_rel = Path(__import__("os").path.relpath(src.resolve(), candidate_dir.resolve())).as_posix()
                lines = filelist.read_text(encoding="utf-8", errors="replace").splitlines()
                lines = [line for line in lines if line.strip().replace("\\", "/") != original_rel]
                filelist.write_text("\n".join(lines) + "\n", encoding="utf-8")
            except OSError:
                pass
    if str(candidate.get("module", "")) == "VX_tcu_bhf_fp8mul" and hardfloat.exists():
        for name in ("HardFloat_primitives.v", "HardFloat_rawFN.v", "addRecFN.v", "fNToRecFN.v", "mulRecFN.v", "recFNToFN.v", "isSigNaNRecFN.v"):
            path = hardfloat / name
            if path.exists():
                extra_sources.append(path)
        # The HardFloat conversion path instantiates Vortex's leading-zero
        # counter through a source-level reference that the crawler does not
        # see inside the included vendor files.
        extra_sources.extend([
            repo / "hw" / "rtl" / "libs" / "VX_lzc.sv",
            repo / "hw" / "rtl" / "libs" / "VX_find_first.sv",
            repo / "hw" / "rtl" / "tcu" / "bhf" / "bsg_counting_leading_zeros.sv",
        ])

    lines = filelist.read_text(encoding="utf-8", errors="replace").splitlines()
    existing = {line.strip().replace("\\", "/") for line in lines}
    added_includes: list[str] = []
    added_sources: list[str] = []
    for path in include_dirs:
        if not path.exists():
            continue
        rel = Path(__import__("os").path.relpath(path.resolve(), candidate_dir.resolve())).as_posix()
        entry = "-I" + rel
        if entry not in existing:
            lines.append(entry)
            existing.add(entry)
            added_includes.append(str(path))
    for path in extra_sources:
        if not path.exists():
            continue
        rel = Path(__import__("os").path.relpath(path.resolve(), candidate_dir.resolve())).as_posix()
        if rel not in existing:
            lines.append(rel)
            existing.add(rel)
            added_sources.append(str(path))
    filelist.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"status": "PASS", "include_roots": added_includes, "sources": added_sources}


def augment_cva6_filelist(candidate: Mapping[str, Any], candidate_dir: Path, workdir: Path) -> dict[str, Any]:
    """Add the fixed-config conversion package used by typed CVA6 adapters.

    The crawler only sees ``build_config_pkg`` when a top-level module
    references it directly.  CVA6's leaf units inherit the package-derived
    configuration through a type parameter, so the dependency is otherwise
    absent from their standalone filelists.  Keep one fixed CV64A6 profile
    for every CVA6 candidate; this prevents the default ``cva6_cfg_empty``
    from creating zero-width vectors in both scalar and typed wrappers.
    """
    filelist = candidate_dir / "candidate.f"
    path = workdir / "repos" / "cva6" / "core" / "include" / "build_config_pkg.sv"
    if not filelist.exists() or not path.exists():
        return {"status": "MISSING", "sources": []}
    lines = filelist.read_text(encoding="utf-8", errors="replace").splitlines()
    # Older crawler profiles leave a self-contained ``pycircuit_validate_*``
    # context in the generated filelist.  Those contexts include the same
    # CVA6 packages that we add below, so slang reports duplicate package
    # definitions (and Yosys refuses to elaborate the candidate).  The
    # runtime campaign supplies its own adapter/testbench; discard only these
    # generated validation contexts, never an upstream RTL source.
    lines = [line for line in lines if "_generated/pycircuit_validate_" not in line.replace("\\", "/")]
    # A standalone CVA6 leaf needs the user profile, config conversion,
    # arithmetic/operation enums and RISC-V constants even when the crawler
    # did not see an explicit package import in the module header.
    package_paths = [
        path,
        workdir / "repos" / "cva6" / "core" / "include" / "cv64a6_imafdc_sv39_config_pkg.sv",
        workdir / "repos" / "cva6" / "core" / "include" / "ariane_pkg.sv",
        workdir / "repos" / "cva6" / "core" / "include" / "config_pkg.sv",
        workdir / "repos" / "cva6" / "core" / "include" / "riscv_pkg.sv",
    ]
    existing = {line.strip().replace("\\", "/") for line in lines}
    changed = False
    added_sources: list[str] = []
    for package_path in package_paths:
        if not package_path.exists():
            continue
        rel = Path(__import__("os").path.relpath(package_path.resolve(), candidate_dir.resolve())).as_posix()
        if rel in existing:
            continue
        # Keep package sources before RTL modules and the generated wrapper.
        insert_at = next((idx for idx, line in enumerate(lines) if "/core/" in line and line.strip() and not line.strip().startswith("-")), len(lines))
        lines.insert(insert_at, rel)
        existing.add(rel)
        added_sources.append(str(package_path))
        changed = True
    # Persist the generated-context pruning even when build_config_pkg was
    # already present in a resumed candidate filelist.
    filelist.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"status": "PASS", "sources": added_sources if changed else []}


def augment_blackparrot_filelist(candidate: Mapping[str, Any], candidate_dir: Path, workdir: Path) -> dict[str, Any]:
    """Materialise source-verified BlackParrot fixed-profile overlays.

    ``bp_sacc_scratchpad`` is an accelerator *scratchpad* endpoint, but its
    public BedRock stream pins were written using ``acache_fill_width_p``.
    That localparam is intentionally zero when ``cac_x_dim_p`` is disabled,
    producing illegal ``logic[-1:0]`` ports even in the repository's own
    scratchpad profile.  The connected BedRock register uses the ordinary
    ``bedrock_fill_width_p`` (128 bits in the checked-in profile), so render a
    local overlay with that source-level correction and leave the checkout
    untouched.
    """
    if str(candidate.get("source_project", "")) != "blackparrot" or str(candidate.get("module", "")) != "bp_sacc_scratchpad":
        return {"status": "SKIP", "sources": []}
    filelist = candidate_dir / "candidate.f"
    src = workdir / "repos" / "blackparrot" / "bp_top" / "src" / "v" / "bp_sacc_scratchpad.sv"
    if not filelist.exists() or not src.exists():
        return {"status": "MISSING", "sources": []}
    try:
        text = src.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return {"status": "MISSING", "sources": []}
    # Restrict the replacement to the two interface declarations.  The
    # source has no other acache references, but keeping the count explicit
    # prevents silently changing a future datapath use.
    patched, count = re.subn(r"(\[(?:acache_fill_width_p)-1:0\])", "[bedrock_fill_width_p-1:0]", text)
    if count < 2:
        return {"status": "SKIP", "sources": []}
    overlay = candidate_dir.parent.parent.parent / "generated" / "blackparrot" / "bp_sacc_scratchpad_fixed.sv"
    overlay.parent.mkdir(parents=True, exist_ok=True)
    overlay.write_text(patched, encoding="utf-8")
    lines = filelist.read_text(encoding="utf-8", errors="replace").splitlines()
    original_rel = Path(__import__("os").path.relpath(src.resolve(), candidate_dir.resolve())).as_posix()
    lines = [line for line in lines if line.strip().replace("\\", "/") != original_rel]
    overlay_rel = Path(__import__("os").path.relpath(overlay.resolve(), candidate_dir.resolve())).as_posix()
    if overlay_rel not in {line.strip().replace("\\", "/") for line in lines}:
        lines.append(overlay_rel)
    filelist.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"status": "PASS", "sources": [str(overlay)], "replacement_count": count}


def normalize_pulp_axi_order(candidate_dir: Path, candidate: Mapping[str, Any] | None = None, workdir: Path | None = None) -> None:
    """Place AXI interface/package declarations before users in the filelist.

    The dependency scanner follows module edges but an SV interface used as a
    modport is not an edge.  For the CDC endpoint façades this previously left
    ``axi_cdc_src.sv`` before ``axi_intf.sv``; Verilator then reports the
    parent's AXI_BUS as unconnected and aborts before elaboration.
    """
    path = candidate_dir / "candidate.f"
    if not path.exists():
        return
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    if candidate is not None and workdir is not None and str(candidate.get("module", "")) == "axi_xbar_unmuxed_intf":
        dep = workdir / "repos" / "pulp_axi" / "src" / "axi_demux_simple.sv"
        if dep.exists():
            rel = Path(__import__("os").path.relpath(dep.resolve(), candidate_dir.resolve())).as_posix()
            if rel not in {line.strip().replace("\\", "/") for line in lines}:
                lines.append(rel)
    def rank(line: str) -> tuple[int, str]:
        name = Path(line.strip()).name
        if name == "axi_pkg.sv":
            return (0, line)
        if name == "cc_pkg.sv":
            return (0, line)
        if name == "axi_intf.sv":
            return (1, line)
        if name == "axi_demux_simple.sv":
            return (2, line)
        if name in {"axi_cdc_src.sv", "axi_cdc_dst.sv", "axi_cdc.sv"}:
            return (3, line)
        return (3, line)
    header = [line for line in lines if line.strip().startswith("//") or line.strip().startswith("-I")]
    sources = [line for line in lines if line not in header]
    ordered = sorted(enumerate(sources), key=lambda item: (rank(item[1]), item[0]))
    path.write_text("\n".join(header + [line for _, line in ordered]) + "\n", encoding="utf-8")


def _render_openpiton_pyv(text: str) -> str:
    """Render the static/fallback part of an OpenPiton ``*.pyv`` template.

    OpenPiton checks in a handful of generated Verilog headers and SRAM
    wrappers as ``foo.v.pyv``/``foo.h.pyv``.  They are valid RTL after the
    project's Python template pass, but the frozen source cache intentionally
    keeps the templates too.  The v0.14 line scanner only indexes ``.v`` and
    ``.sv`` and therefore drops these dependencies.  For the fixed standalone
    profile we remove the template blocks and activate the checked-in fallback
    ``//`define`` values.  No upstream checkout is modified; the rendered copy
    lives in the per-candidate build directory and is recorded in the
    manifest.
    """
    out: list[str] = []
    in_template = False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped == "<%":
            in_template = True
            continue
        if stripped == "%>":
            in_template = False
            continue
        if in_template:
            continue
        # Most pyv files carry a legal fallback immediately below the Python
        # block.  Enabling it gives us deterministic dimensions (e.g. the
        # L2 MSHR and LMQ slices) without guessing from a missing macro.
        if re.match(r"^\s*//\s*`define\b", line):
            line = re.sub(r"^(\s*)//\s*", r"\1", line, count=1)
        out.append(line)
    rendered = "\n".join(out).rstrip() + "\n"
    # ``bw_r_dtlb.v.pyv`` contains a Mako/Python loop whose generated
    # ``if/else if`` chain is removed by this lightweight renderer.  The
    # static trailing ``else`` would then have no matching ``if`` and
    # Verilator rejects the rendered copy.  Materialize the smallest legal
    # fixed-profile chain in the generated file; upstream RTL is untouched.
    dangling = re.compile(
        r"(?P<head>tlb_entry_replace_d1\s*=\s*\{`TLB_ENTRIES(?:-1)?\{1'b0\}\};\s*"
        r"// Priority is given to entry0)\s*"
        r"else\s*begin\s*"
        r"tlb_entry_replace_d1\[`TLB_ENTRIES-1\]\s*=\s*1'b1;\s*"
        r"end",
        flags=re.S,
    )
    rendered = dangling.sub(
        r"\g<head>\n"
        "      if (~used[0]) begin\n"
        "        tlb_entry_replace_d1[0] = ~used[0];\n"
        "      end else begin\n"
        "        tlb_entry_replace_d1[`TLB_ENTRIES-1] = 1'b1;\n"
        "      end",
        rendered,
    )
    # ``bw_r_dcd.v.pyv`` also uses GenFor for the data-cache way declarations
    # and column-mux assignments.  The fixed-profile renderer intentionally
    # does not execute arbitrary Python/Mako, so those declarations otherwise
    # disappear while their static consumers remain.  Materialize the
    # four-way generic profile here.  The declarations are deliberately
    # ``logic``: in the FPGA profile they are written by the behavioral RAM
    # process, while in the SRAM profile the same signals are driven by the
    # SRAM macro outputs.  Only one preprocessor branch is active at a time.
    if (
        "dcache_alt_data_w0_m" in text
        and "dcache_rdata_wb" in text
        and "L1D_DATA_ENTRY_WIDTH" in text
        and not re.search(r"^\s*(?:wire|logic|reg)\s+\[63:0\]\s+dcache_rdata_w0_m", rendered, re.M)
    ):
        fixed_cache = """
// Fixed standalone profile: four L1D ways (materialized from GenFor).
logic [`L1D_DATA_ENTRY_WIDTH-1:0] w0 [127:0];
logic [`L1D_DATA_ENTRY_WIDTH-1:0] w1 [127:0];
logic [`L1D_DATA_ENTRY_WIDTH-1:0] w2 [127:0];
logic [`L1D_DATA_ENTRY_WIDTH-1:0] w3 [127:0];
logic [`L1D_DATA_ENTRY_WIDTH-1:0] temp_w0a, temp_w1a, temp_w2a, temp_w3a;
logic [`L1D_DATA_ENTRY_WIDTH-1:0] temp_w0a_reg, temp_w1a_reg, temp_w2a_reg, temp_w3a_reg;
logic [`L1D_DATA_ENTRY_WIDTH-1:0] temp_w0, temp_w1, temp_w2, temp_w3;
wire [`L1D_DATA_ENTRY_WIDTH-1:0] way0_write_mask = {144{dcache_wr_rway_e[0]}} & way_mask_e;
wire [`L1D_DATA_ENTRY_WIDTH-1:0] way1_write_mask = {144{dcache_wr_rway_e[1]}} & way_mask_e;
wire [`L1D_DATA_ENTRY_WIDTH-1:0] way2_write_mask = {144{dcache_wr_rway_e[2]}} & way_mask_e;
wire [`L1D_DATA_ENTRY_WIDTH-1:0] way3_write_mask = {144{dcache_wr_rway_e[3]}} & way_mask_e;
wire [7:0] gen_dcache_parity_w0_m, gen_dcache_parity_w1_m, gen_dcache_parity_w2_m, gen_dcache_parity_w3_m;
wire [7:0] rd_parity_err_w0_m, rd_parity_err_w1_m, rd_parity_err_w2_m, rd_parity_err_w3_m;
wire [7:0] dcache_rparity_w0_m, dcache_rparity_w1_m, dcache_rparity_w2_m, dcache_rparity_w3_m;
wire [63:0] dcache_rdata_w0_m, dcache_rdata_w1_m, dcache_rdata_w2_m, dcache_rdata_w3_m;
logic [63:0] dcache_rdata_w0_wb, dcache_rdata_w1_wb, dcache_rdata_w2_wb, dcache_rdata_w3_wb;
wire [7:0] dcache_rdata_msb_w0_m, dcache_rdata_msb_w1_m, dcache_rdata_msb_w2_m, dcache_rdata_msb_w3_m;
wire [63:0] rdata_w0_m, rdata_w1_m, rdata_w2_m, rdata_w3_m;

// Select the lower/upper 64-bit column from each 144-bit way entry.
assign dcache_rdata_w0_m = ~dcache_rwaddr_m[3] ? temp_w0a[`L1D_DATA_ENTRY_WIDTH-1:80] : temp_w0a[79:16];
assign dcache_rdata_w1_m = ~dcache_rwaddr_m[3] ? temp_w1a[`L1D_DATA_ENTRY_WIDTH-1:80] : temp_w1a[79:16];
assign dcache_rdata_w2_m = ~dcache_rwaddr_m[3] ? temp_w2a[`L1D_DATA_ENTRY_WIDTH-1:80] : temp_w2a[79:16];
assign dcache_rdata_w3_m = ~dcache_rwaddr_m[3] ? temp_w3a[`L1D_DATA_ENTRY_WIDTH-1:80] : temp_w3a[79:16];
assign dcache_rparity_w0_m = ~dcache_rwaddr_m[3] ? temp_w0a[15:8] : temp_w0a[7:0];
assign dcache_rparity_w1_m = ~dcache_rwaddr_m[3] ? temp_w1a[15:8] : temp_w1a[7:0];
assign dcache_rparity_w2_m = ~dcache_rwaddr_m[3] ? temp_w2a[15:8] : temp_w2a[7:0];
assign dcache_rparity_w3_m = ~dcache_rwaddr_m[3] ? temp_w3a[15:8] : temp_w3a[7:0];
"""
        marker = "wire  [`L1D_DATA_ENTRY_WIDTH-1:0]   way_mask ;"
        if marker in rendered:
            rendered = rendered.replace(marker, fixed_cache + "\n" + marker, 1)
        else:
            rendered = fixed_cache + "\n" + rendered
    return rendered


def augment_openpiton_filelist(candidate: Mapping[str, Any], candidate_dir: Path, workdir: Path) -> dict[str, Any]:
    """Close OpenPiton's generated ``.pyv`` and FPGA primitive dependencies.

    The OpenPiton checkout is distributed with a few Python-templated source
    files rather than the generated ``.v`` files referenced by its FuseSoC
    core files.  A standalone top consequently reports missing modules such as
    ``l2_mshr``/``bw_r_dcd`` even though the corresponding ``.v.pyv`` exists in
    the local clone.  Materialize only the transitive ``.pyv`` modules needed
    by the unresolved edges, recursively, and add a small behavioral BUFGMUX
    model for the OpenCores SD clock divider (the Xilinx primitive is replaced
    by an equivalent 2:1 combinational mux in the fixed generic profile).
    """
    if str(candidate.get("source_project", "")) != "openpiton":
        return {"status": "SKIP", "sources": [], "headers": [], "unresolved": []}
    filelist = candidate_dir / "candidate.f"
    manifest_path = candidate_dir / "manifest.json"
    manifest = read_json(manifest_path, {})
    repo = workdir / "repos" / "openpiton"
    if not filelist.exists() or not repo.exists() or not isinstance(manifest, dict):
        return {"status": "MISSING", "sources": [], "headers": [], "unresolved": []}

    generated_root = (candidate_dir / "_generated").resolve()
    generated_root.mkdir(parents=True, exist_ok=True)
    pyv_root = generated_root / "openpiton_pyv"
    pyv_root.mkdir(parents=True, exist_ok=True)
    include_root = repo / "piton" / "design" / "include"
    rendered_headers: list[str] = []

    fixed_headers = {
        "define.h": "`ifndef NOC_X_WIDTH\n`define NOC_X_WIDTH 8\n`define NOC_Y_WIDTH 8\n`define NOC_FBITS_WIDTH 4\n`define NOC_NODEID_WIDTH 34\n`endif\n",
        "l2.h": "`ifndef L2_WAYS\n`define L2_WAYS 4\n`define L2_WAYS_WIDTH 2\n`define L2_TAG_INDEX_WIDTH 8\n`define L2_TAG_WIDTH 26\n`define L2_TAG_WAY_WIDTH 26\n`define L2_TAG_ARRAY_WIDTH 104\n`define L2_TAG_INDEX 13:6\n`define L2_TAG 39:14\n`endif\n",
        # ``lsu.h.pyv`` and ``ifu.h.pyv`` generate these four/five defines
        # from pyhplib at build time.  The source cache deliberately keeps
        # only the template, so the old renderer removed the whole dynamic
        # block and left downstream slices such as ``LMQ_SZ_LO`` and
        # ``IC_SET_IDX_HI`` undefined.  Materialize the checked-in generic
        # OpenPiton profile here; the remaining static portions of each pyv
        # file are appended below by ``_render_openpiton_pyv``.
        "lsu.h": (
            "`ifndef L1D_ENTRY_COUNT\n"
            "`define L1D_ENTRY_COUNT 512\n"
            "`define L1D_SET_IDX_HI 6\n"
            "`define L1D_WAY_COUNT 4\n"
            "`define L1D_WAY_WIDTH 2\n"
            "`define TLB_CSM_WIDTH 33\n"
            "`define TLB_CSM 32:0\n"
            "`define TLB_CSM_LOCAL 31:0\n"
            "`define TLB_CSM_HDID 31:22\n"
            "`define TLB_CSM_HD_SIZE 21:16\n"
            "`define TLB_CSM_SDID 15:6\n"
            "`define TLB_CSM_LSID 5:0\n"
            "`endif\n"
        ),
        "ifu.h": (
            "`ifndef IC_SZ\n"
            "`define IC_SZ 16384\n"
            "`define IC_SET_IDX_HI 6\n"
            "`define IC_NUM_WAY 4\n"
            "`define IC_WAY_MASK 1:0\n"
            "`define IC_WAY_IDX_WIDTH 2\n"
            "`endif\n"
            "`ifndef IC_LINE_SZ\n"
            "`define IC_LINE_SZ 32\n"
            "`endif\n"
        ),
    }

    # Header templates use the basename requested by the RTL (l2.h, lsu.h,
    # ...).  Render into the already-listed generated include directory so
    # normal `include directives resolve without source edits.
    for src in sorted(include_root.glob("*.h.pyv")):
        dst = generated_root / src.name[:-4]  # ``l2.h.pyv`` -> ``l2.h``
        # lsu.h's template fallback contains an unconditional ``LMQ_WIDTH=65``
        # definition.  That value masks the richer lsu.tmp.h shim (which then
        # skips TLB/L1D macros under its `ifndef LMQ_WIDTH guard), so use only
        # the fixed generated prefix for this header.  Other headers retain
        # their static portions and comments.
        # Keep the static body for every header, including lsu.h.  Earlier
        # versions used only the four L1D defines for lsu.h to avoid an
        # unconditional LMQ_WIDTH fallback; that also discarded the valid
        # STB/LMQ/TLB bit-field macros needed by the standalone LSU tops.
        rendered = fixed_headers.get(dst.name, "") + _render_openpiton_pyv(src.read_text(encoding="utf-8", errors="replace"))
        if dst.name == "define.h":
            # The dynamic template normally supplies these aliases from the
            # pyhplib configuration.  The network header fixes the physical
            # widths for the generic 2-D mesh/XBAR profile used here.
            prefix = (
                "`ifndef NOC_X_WIDTH\n`define NOC_X_WIDTH 8\n`endif\n"
                "`ifndef NOC_Y_WIDTH\n`define NOC_Y_WIDTH 8\n`endif\n"
                "`ifndef NOC_FBITS_WIDTH\n`define NOC_FBITS_WIDTH 4\n`endif\n"
            )
            rendered = prefix + rendered
        dst.write_text(rendered, encoding="utf-8")
        rendered_headers.append(str(dst))

    # The generated ``*.tmp.h`` shims are intentionally small.  Include the
    # rendered canonical headers so macro users get the complete fixed
    # profile rather than only the subset embedded in the crawler manifest.
    for temp, header in (("define.tmp.h", "define.h"), ("l2.tmp.h", "l2.h"), ("lsu.tmp.h", "lsu.h"), ("ifu.tmp.h", "ifu.h")):
        path = generated_root / temp
        if not path.exists():
            continue
        body = path.read_text(encoding="utf-8", errors="replace")
        directive = f'`include "{header}"'
        if directive not in body:
            path.write_text(directive + "\n" + body, encoding="utf-8")

    lines = filelist.read_text(encoding="utf-8", errors="replace").splitlines()
    existing = {line.strip().replace("\\", "/") for line in lines}
    added_sources: list[str] = []

    def add_source(path: Path) -> None:
        rel = Path(__import__("os").path.relpath(path.resolve(), candidate_dir.resolve())).as_posix()
        if rel not in existing:
            lines.append(rel)
            existing.add(rel)
            added_sources.append(str(path))

    # The top-level LSU source selects these helpers through legacy macro
    # branches that the line-oriented crawler cannot follow.  They are real
    # OpenPiton sources in the frozen checkout (not black-box replacements),
    # so close this known profile explicitly.  ``sram_l1d_tag`` is a pyv
    # template and is rendered into the per-candidate overlay just like the
    # other generated SRAM files.
    if str(candidate.get("module", "")) in {"lsu", "lsu_nospu_wrap"}:
        fixed_lsu_sources = [
            repo / "piton" / "design" / "chip" / "tile" / "sparc" / "lsu" / "rtl" / "lsu_dcache_lfsr.v",
            repo / "piton" / "design" / "chip" / "tile" / "sparc" / "lsu" / "rtl" / "lsu_asi_decode.v",
            repo / "piton" / "design" / "chip" / "tile" / "sparc" / "lsu" / "rtl" / "lsu_rrobin_picker2.v",
            # The LSU closure reaches the generated register-file bank
            # (bw_r_rf32x80), whose mux instance is defined in the legacy
            # datapath primitive library rather than next to the LSU RTL.
            # The line scanner does not follow that indirect cell edge, so
            # include the real OpenPiton library explicitly.
            repo / "piton" / "design" / "chip" / "tile" / "common" / "rtl" / "swrvr_dlib.v",
        ]
        for source in fixed_lsu_sources:
            if source.exists():
                add_source(source)
        # In the generic standalone profile OpenPiton comments out the fuse
        # redundancy header but leaves the LSU's dcache output ports wired to
        # constants.  That creates a genuine multiple-driver condition which
        # Yosys rejects (the simulator tolerates it).  Keep the source logic
        # intact and materialize a narrow overlay that leaves these unused
        # scan/fuse outputs open, matching the commented-out header path.
        lsu_src = repo / "piton" / "design" / "chip" / "tile" / "sparc" / "lsu" / "rtl" / "lsu.v"
        if lsu_src.exists():
            try:
                lsu_text = lsu_src.read_text(encoding="utf-8", errors="replace")
                lsu_fixed, replace_count = re.subn(
                    r"\.dcd_fuse_repair_value\s*\(dcd_fuse_repair_value\[7:0\]\)",
                    ".dcd_fuse_repair_value ()",
                    lsu_text,
                )
                lsu_fixed, count_en = re.subn(
                    r"\.dcd_fuse_repair_en\s*\(dcd_fuse_repair_en\[1:0\]\)",
                    ".dcd_fuse_repair_en    ()",
                    lsu_fixed,
                )
                replace_count += count_en
                if replace_count:
                    overlay = pyv_root / "lsu_fixed.v"
                    overlay.write_text(lsu_fixed, encoding="utf-8")
                    original_rel = Path(__import__("os").path.relpath(lsu_src.resolve(), candidate_dir.resolve())).as_posix()
                    lines[:] = [line for line in lines if line.strip().replace("\\", "/") != original_rel]
                    existing.clear()
                    existing.update(line.strip().replace("\\", "/") for line in lines)
                    add_source(overlay)
            except OSError:
                pass
        tag_template = repo / "piton" / "design" / "chip" / "tile" / "sparc" / "srams" / "rtl" / "sram_wrappers" / "sram_l1d_tag.v.pyv"
        if tag_template.exists():
            tag_rendered = pyv_root / "sram_l1d_tag.v"
            tag_text = _render_openpiton_pyv(tag_template.read_text(encoding="utf-8", errors="replace"))
            # ``sram_l1d_tag.v.pyv`` delegates its complete body to
            # ``pyhplib.MakeGenericCacheDefine``.  There is no checked-in
            # Verilog fallback for the generic profile, so the lightweight
            # renderer would otherwise leave an include-only file and
            # Verilator would report a missing module.  Materialize the
            # equivalent single-clock, byte-writeable SRAM model with the
            # dimensions supplied by the fixed OpenPiton headers.
            if not re.search(r"(?m)^\s*module\s+sram_l1d_tag\b", tag_text):
                tag_text += """

module sram_l1d_tag (
  input wire MEMCLK,
  input wire RESET_N,
  input wire CE,
  input wire [`L1D_SET_IDX_MASK] A,
  input wire [`L1D_TAG_ARRAY_REAL_WIDTH-1:0] DIN,
  input wire [`L1D_TAG_ARRAY_REAL_WIDTH-1:0] BW,
  input wire RDWEN,
  output wire [`L1D_TAG_ARRAY_REAL_WIDTH-1:0] DOUT,
  input wire [`BIST_OP_WIDTH-1:0] BIST_COMMAND,
  input wire [`SRAM_WRAPPER_BUS_WIDTH-1:0] BIST_DIN,
  output reg [`SRAM_WRAPPER_BUS_WIDTH-1:0] BIST_DOUT,
  input wire [`BIST_ID_WIDTH-1:0] SRAMID
);
  reg [`L1D_TAG_ARRAY_REAL_WIDTH-1:0] mem [0:`L1D_SET_COUNT-1];
  reg [`L1D_TAG_ARRAY_REAL_WIDTH-1:0] dout_f;
  integer idx;
  initial begin
    for (idx = 0; idx < `L1D_SET_COUNT; idx = idx + 1)
      mem[idx] = '0;
    dout_f = '0;
    BIST_DOUT = '0;
  end
  always @(posedge MEMCLK) begin
    if (CE) begin
      if (!RDWEN)
        mem[A] <= (DIN & BW) | (mem[A] & ~BW);
      else
        dout_f <= mem[A];
    end
  end
  assign DOUT = dout_f;
endmodule
"""
            if not tag_rendered.exists() or tag_rendered.read_text(encoding="utf-8", errors="replace") != tag_text:
                tag_rendered.write_text(tag_text, encoding="utf-8")
            add_source(tag_rendered)

    # Index module declarations in the templated files once.  Exact basename
    # matches cover the common case; the declaration map also handles a
    # template that contains several small SRAM helper modules.
    module_files: dict[str, Path] = {}
    templated_sources = sorted(repo.rglob("*.v.pyv")) + sorted(repo.rglob("*.sv.pyv"))
    for src in templated_sources:
        try:
            content = src.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for name in re.findall(r"(?m)^\s*module\s+([A-Za-z_][A-Za-z0-9_$]*)", content):
            module_files.setdefault(name, src)

    unresolved = list(manifest.get("unresolved_dependencies", []))
    queue = [str(edge.get("dependency_name", "")) for edge in unresolved if edge.get("dependency_kind") == "submodule"]
    resolved_names: set[str] = set()
    # The scanner can report the same concrete OpenPiton source twice (once
    # from the generated filelist and once from a directory walk) as an
    # ``ambiguous`` edge.  It is not a real ambiguity when all alternatives
    # normalize to one path; retain that source and close the edge.
    for edge in unresolved:
        if edge.get("dependency_kind") != "submodule" or edge.get("resolution_status") != "ambiguous":
            continue
        alternatives = [item for item in str(edge.get("resolved_file", "")).split("|") if item]
        unique = list(dict.fromkeys(alternatives))
        if len(unique) == 1:
            concrete = repo / unique[0]
            if concrete.exists():
                add_source(concrete)
                resolved_names.add(str(edge.get("dependency_name", "")))
    while queue:
        name = queue.pop(0)
        if not name or name in resolved_names:
            continue
        src = module_files.get(name)
        if src is None:
            continue
        resolved_names.add(name)
        dst = pyv_root / src.name[:-4]  # normalize extension for Verilator/slang
        rendered_source = _render_openpiton_pyv(src.read_text(encoding="utf-8", errors="replace"))
        # Re-write an existing generated copy when the renderer/profile is
        # improved between resumable campaign invocations.  Keeping the old
        # file here would leave a stale dangling ``else`` (or stale macro
        # values) in the case directory forever.
        if not dst.exists() or dst.read_text(encoding="utf-8", errors="replace") != rendered_source:
            dst.write_text(rendered_source, encoding="utf-8")
        add_source(dst)
        # Discover additional templated instances so the closure is genuinely
        # transitive instead of marking only the first missing edge resolved.
        body = dst.read_text(encoding="utf-8", errors="replace")
        for inst in re.findall(r"(?m)^\s*([A-Za-z_][A-Za-z0-9_$]*)\s+[A-Za-z_][A-Za-z0-9_$]*(?:\s*#\s*\([^;]*?\))?\s*\(", body):
            if inst in module_files and inst not in resolved_names:
                queue.append(inst)

    # A resumable run may already have an empty unresolved-dependency list,
    # so the queue above is empty even though a previously generated pyv copy
    # was rendered by an older version of this helper.  Refresh every existing
    # generated template by basename to make renderer/profile changes
    # effective without deleting the campaign output.
    for dst in pyv_root.iterdir():
        if not dst.is_file():
            continue
        # ``sram_l1d_tag.v`` is materialized below from an include-only pyv
        # template.  Do not let the generic refresh pass overwrite that
        # generated SRAM body with the template-only rendering.
        if dst.name == "sram_l1d_tag.v":
            continue
        source = next((item for item in templated_sources if item.name[:-4] == dst.name), None)
        if source is None:
            continue
        rendered_source = _render_openpiton_pyv(source.read_text(encoding="utf-8", errors="replace"))
        if dst.read_text(encoding="utf-8", errors="replace") != rendered_source:
            dst.write_text(rendered_source, encoding="utf-8")

    # OpenCores' SD divider uses a Xilinx BUFGMUX primitive.  Add an explicit
    # generic implementation only for this candidate; it preserves the
    # selected-clock behavior and is suitable for both Verilator and Yosys.
    if str(candidate.get("module", "")) == "sd_clock_divider":
        vendor = pyv_root / "openpiton_generic_primitives.v"
        if not vendor.exists():
            vendor.write_text(
                "// Generic replacement for Xilinx BUFGMUX used by sd_clock_divider.\n"
                "module BUFGMUX(input wire I0, input wire I1, input wire S, output wire O);\n"
                "  assign O = S ? I1 : I0;\n"
                "endmodule\n",
                encoding="utf-8",
            )
        add_source(vendor)
        resolved_names.add("BUFGMUX")

    # Legacy OpenPiton generated primitives rely on macros from ``define.h``.
    # Some generated files (notably ``bw_r_dcd.v``) intentionally omit the
    # include because the full chip filelist supplies it earlier.  A
    # standalone candidate must preserve that ordering as well: make the
    # materialized LSU top/header carrier appear before the generated SRAM
    # implementations.  Without this stable order Verilator reports
    # ``BIST_ID_L1_DCACHE_W01``/``W23`` as undefined even though the real
    # header is present in the closure.
    if str(candidate.get("module", "")) in {"lsu", "lsu_nospu_wrap"}:
        indexed_entries = list(enumerate(lines))
        fixed_prefix = [line for line in lines if line.strip().startswith("//") or not line.strip() or line.strip().startswith("-I")]
        source_entries = [line for line in lines if line not in fixed_prefix]
        rank_map = {"lsu_fixed.v": 0, "sram_l1d_tag.v": 1, "bw_r_rf32x80.v": 2}
        original_order = {line: idx for idx, line in indexed_entries}
        source_entries.sort(key=lambda line: (rank_map.get(Path(line.strip()).name.lower(), 10), original_order.get(line, 0)))
        lines = fixed_prefix + source_entries

    filelist.write_text("\n".join(lines) + "\n", encoding="utf-8")

    remaining: list[dict[str, Any]] = []
    for edge in unresolved:
        name = str(edge.get("dependency_name", ""))
        if edge.get("dependency_kind") == "submodule" and name in resolved_names:
            edge["resolution_status"] = "resolved_generated"
            edge["resolved_file"] = "@generated/openpiton_pyv/" + name
        else:
            remaining.append(edge)
    manifest["unresolved_dependencies"] = remaining
    manifest["generated_files"] = sorted(set(manifest.get("generated_files", [])) | set(rendered_headers) | set(added_sources))
    manifest["generated_header_files"] = sorted(set(manifest.get("generated_header_files", [])) | set(rendered_headers))
    manifest["external_files"] = sorted(set(manifest.get("external_files", [])) | set(added_sources))
    if not remaining:
        manifest["closure_status"] = "COMPLETE"
        manifest["closure_status_original"] = manifest.get("closure_status_original", "PARTIAL")
    json_dump(manifest_path, manifest)
    return {"status": "PASS" if not remaining else "PARTIAL", "sources": added_sources, "headers": rendered_headers, "unresolved": remaining}


def vortex_unresolved_is_supported(manifest: Mapping[str, Any], support: Mapping[str, Any]) -> bool:
    """Return whether remaining static Vortex edges are covered by support."""
    if support.get("status") != "PASS":
        return False
    unresolved = manifest.get("unresolved_dependencies", [])
    for edge in unresolved:
        kind = str(edge.get("dependency_kind", ""))
        name = str(edge.get("dependency_name", ""))
        if kind == "include" and name in VORTEX_GENERATED_INCLUDES:
            continue
        # Any module edge should have been explicitly pruned and re-run with
        # the support source in the filelist.  Treating it as supported here
        # would hide a real missing unit.
        return False
    return True


def load_candidates(path: Path) -> list[dict[str, Any]]:
    """Load the v0.14 structural inventory and de-duplicate stable tops."""
    with path.open(newline="", encoding="utf-8") as stream:
        rows = list(csv.DictReader(stream))
    result: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str, str]] = set()
    for row in rows:
        key = (row.get("source_project", ""), row.get("module", ""), row.get("file", ""), row.get("commit_sha", ""))
        if not all(key[:3]) or key in seen:
            continue
        try:
            row["ports"] = json.loads(row.get("ports_json", "[]"))
        except json.JSONDecodeError:
            row["ports"] = []
        row["ports"] = [normalize_port(port) for port in row["ports"] if isinstance(port, dict)]
        try:
            row["parameters"] = json.loads(row.get("parameters_json", "[]"))
        except json.JSONDecodeError:
            row["parameters"] = []
        recover_known_top_metadata(row)
        result.append(row)
        seen.add(key)
    result.sort(key=lambda item: (item.get("source_project", ""), item.get("module", ""), item.get("file", "")))
    return result


