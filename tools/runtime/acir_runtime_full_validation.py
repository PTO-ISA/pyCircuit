def generate_typed_closed_wrapper(candidate: Mapping[str, Any], values: Mapping[str, int]) -> str | None:
    """Build a portless wrapper for packed structs/enums and type parameters.

    Flat scalar wrappers cannot represent AXI/CVA6 typedef ports: leaving a
    type parameter at its RTL default (``logic``) makes every ``.aw``/``.id``
    member access fail in Verilator.  These adapters instantiate the real
    package typedefs and pass explicit, bounded type specializations while
    keeping the public smoke top portless.
    """
    if not typed_closed_wrapper_supported(candidate):
        return None
    project = str(candidate.get("source_project", ""))
    module = str(candidate.get("module", ""))
    vals = {str(key): int(value) for key, value in values.items() if str(key) != "__config_index"}
    if project == "cva6":
        manual = _cva6_manual_typed_wrapper(module)
        if manual is not None:
            return manual
