def _axi_interface_wrapper(module: str, spec: Dict, top: str) -> str:
    lite = module.startswith('axi_lite_')
    count = int(spec.get('count', 2))
    iface = 'AXI_LITE' if lite else 'AXI_BUS'
    params = '.AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32)' if lite else '.AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_ID_WIDTH(4), .AXI_USER_WIDTH(1)'
    if module in {'axi_lite_demux_intf', 'axi_demux_intf'}:
        port_decl = f'''  {iface} #({params}) slv();
  {iface} #({params}) mst [0:{count - 1}]();'''
        call = f'''    .clk_i(clk_i), .rst_ni(rst_ni), .test_i(test_i),
    .slv_aw_select_i(slv_aw_select_i), .slv_ar_select_i(slv_ar_select_i),
    .slv(slv), .mst(mst)'''
        select = '  logic [0:0] slv_aw_select_i, slv_ar_select_i;\n'
        if lite:
            instparams = f'.AxiAddrWidth(32), .AxiDataWidth(32), .NoMstPorts({count}), .MaxTrans(4)'
        else:
            instparams = f'.AXI_ID_WIDTH(4), .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_USER_WIDTH(1), .NO_MST_PORTS({count}), .MAX_TRANS(4)'
    elif module in {'axi_lite_mux_intf', 'axi_mux_intf'}:
        port_decl = f'''  {iface} #({params}) slv [0:{count - 1}]();
  {iface} #({params}) mst();'''
        call = '    .clk_i(clk_i), .rst_ni(rst_ni), .test_i(test_i), .slv(slv), .mst(mst)'
        select = ''
        if lite:
            instparams = f'.AxiAddrWidth(32), .AxiDataWidth(32), .NoSlvPorts({count}), .MaxTrans(4)'
        else:
            instparams = f'.SLV_AXI_ID_WIDTH(4), .MST_AXI_ID_WIDTH(5), .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_USER_WIDTH(1), .NO_SLV_PORTS({count}), .MAX_W_TRANS(4)'
    else:
        raise ValueError(f'Unsupported interface wrapper module {module}')
    return f'''// Auto-generated interface validation context; DUT remains upstream RTL.
module {top};
  logic clk_i, rst_ni, test_i;
{select}{port_decl}
  {module} #({instparams}) dut (
{call}
  );
endmodule
'''


