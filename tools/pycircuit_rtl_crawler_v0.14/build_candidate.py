def _axi_interface_context_wrapper(module: str, spec: Dict, top: str) -> str:
    """Tie off interface ports with real interface instances.

    An interface port is not a legal standalone top-level connection in
    Yosys/Verilator.  Instantiating the matching interface objects gives the
    DUT an elaboration context without flattening or changing its semantics.
    """
    lite = module.startswith("axi_lite_")
    is_dst = module.endswith("_dst_intf")
    is_src = module.endswith("_src_intf")
    is_full = module in {"axi_cdc_intf", "axi_lite_cdc_intf"}
    if not (is_dst or is_src or is_full):
        raise ValueError(f"Unsupported interface context wrapper module {module}")
    log_depth = int(spec.get("log_depth", 1))
    sync_stages = int(spec.get("sync_stages", 3))
    # The upstream lite source endpoint currently declares its synchronous
    # ``src`` port as AXI_BUS (the implementation still uses the lite assign
    # macros).  Match that declaration exactly so the wrapper exposes a real
    # interface rather than masking a source-level mismatch.
    lite_src_uses_full = module == "axi_lite_cdc_src_intf"
    if lite and not lite_src_uses_full:
        bus = "AXI_LITE"
        bus_params = " .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32) "
        async_bus = "AXI_LITE_ASYNC_GRAY"
        async_params = f" .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .LOG_DEPTH({log_depth}) "
        widths = f".AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .LOG_DEPTH({log_depth}), .SYNC_STAGES({sync_stages})"
    elif lite_src_uses_full:
        bus = "AXI_BUS"
        bus_params = " .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_ID_WIDTH(4), .AXI_USER_WIDTH(1) "
        async_bus = "AXI_LITE_ASYNC_GRAY"
        async_params = f" .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .LOG_DEPTH({log_depth}) "
        widths = f".AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .LOG_DEPTH({log_depth}), .SYNC_STAGES({sync_stages})"
    else:
        bus = "AXI_BUS"
        bus_params = " .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_ID_WIDTH(4), .AXI_USER_WIDTH(1) "
        async_bus = "AXI_BUS_ASYNC_GRAY"
        async_params = f" .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_ID_WIDTH(4), .AXI_USER_WIDTH(1), .LOG_DEPTH({log_depth}) "
        widths = f".AXI_ID_WIDTH(4), .AXI_ADDR_WIDTH(32), .AXI_DATA_WIDTH(32), .AXI_USER_WIDTH(1), .LOG_DEPTH({log_depth}), .SYNC_STAGES({sync_stages})"
    if is_dst:
        decl = f"  {async_bus} #({async_params}) src();\n  {bus} #({bus_params}) dst();"
        ports = ".src(src), .dst_clk_i(clk_i), .dst_rst_ni(rst_ni), .dst(dst)"
    elif is_src:
        decl = f"  {bus} #({bus_params}) src();\n  {async_bus} #({async_params}) dst();"
        ports = ".src_clk_i(clk_i), .src_rst_ni(rst_ni), .src(src), .dst(dst)"
    else:
        decl = f"  {bus} #({bus_params}) src();\n  {bus} #({bus_params}) dst();"
        ports = ".src_clk_i(src_clk_i), .src_rst_ni(src_rst_ni), .src(src), .dst_clk_i(dst_clk_i), .dst_rst_ni(dst_rst_ni), .dst(dst)"
    clocks = "  logic clk_i, rst_ni;" if not is_full else "  logic src_clk_i, src_rst_ni, dst_clk_i, dst_rst_ni;"
    return f'''// Auto-generated interface validation context; DUT remains upstream RTL.
module {top};
{clocks}
{decl}
  {module} #({widths}) dut ({ports});
endmodule
'''


