def materialize_validation_wrapper(source: Dict, module: str, outdir: Path, closure: Dict) -> str:
    spec = validation_wrapper_spec(source, module)
    if not spec:
        return module
    kind = str(spec.get('kind', '')).lower()
    top = str(spec.get('top') or f'pycircuit_validate_{safe_name(module)}')
    if kind in {'axi4', 'axi4_cdc'}:
        content = _axi4_wrapper(module, spec, top)
    elif kind == 'axi4_endpoint':
        content = _axi4_endpoint_wrapper(module, spec, top)
    elif kind in {'axi_lite', 'axi_lite_mux'}:
        content = _axi_lite_wrapper(module, spec, top)
    elif kind == 'cva6_btb':
        content = _cva6_btb_wrapper(spec, top)
    elif kind == 'axi4_scalar':
        content = _axi4_scalar_wrapper(module, spec, top)
    elif kind == 'axi_intf':
        content = _axi_interface_wrapper(module, spec, top)
    elif kind in {'axi_cdc_intf', 'axi_cdc_endpoint_intf'}:
        content = _axi_interface_context_wrapper(module, spec, top)
    elif kind == 'cva6_fifo':
        content = _cva6_fifo_wrapper(top)
    else:
        raise ValueError(f'Unsupported validation wrapper kind {kind!r} for {module}')
    target = (outdir / '_generated' / f'{top}.sv').resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding='utf-8')
    closure.setdefault('external_files', []).append(str(target))
    closure.setdefault('generated_files', []).append(str(target))
    # The wrapper supplies concrete types, so the original generic module and
    # its normal dependencies remain in the closure and retain provenance.
    module_names = set(re.findall(r'(?m)^\s*module\s+([A-Za-z_][A-Za-z0-9_$]*)', content))
    for edge in closure.get('unresolved', []):
        if edge.get('dependency_kind') == 'submodule' and edge.get('dependency_name') in module_names:
            edge['resolution_status'] = 'resolved_generated'
            edge['resolved_file'] = '@generated/' + target.name
    closure['external_files'] = sorted(set(closure.get('external_files', [])))
    closure['generated_files'] = sorted(set(closure.get('generated_files', [])))
    closure['closure_status'] = 'COMPLETE' if not closure.get('unresolved') else 'PARTIAL'
    return top


def add_declared_include_roots(model: RepositoryModel, source: Dict, closure: Dict,
                               primary: bool = True) -> None:
    """Seed the filelist with configured include/vendor roots.

    Static dependency discovery only adds a directory after it sees an
    include in a parsed file.  A number of generated and legacy RTL trees
    include headers indirectly (or through macro-expanded paths), so those
    roots must be present even when no direct edge was parsed.  Keep primary
    checkout paths relative and sibling-repository paths absolute, matching
    the rest of the candidate filelist format.
    """
    fields = ("include_hints", "vendor_hints")
    for field in fields:
        for raw in source.get(field, []) or []:
            rel = str(raw).replace('\\', '/').strip().strip('/')
            if not rel or rel == '.':
                continue
            path = (model.repo_dir / rel).resolve()
            # A hint may name a header rather than a directory.  In that
            # case Verilator needs the containing directory on its -I path.
            root = path.parent if path.is_file() else path
            if not root.exists():
                # Keep the configured path visible in the manifest/filelist;
                # a missing sparse path is actionable and should not silently
                # turn into an unresolved include later in the run.
                root = path
            if primary:
                closure.setdefault('include_roots', []).append(rel if root == path else str(Path(rel).parent.as_posix()))
            else:
                closure.setdefault('external_include_roots', []).append(str(root))
    closure['include_roots'] = sorted(set(closure.get('include_roots', [])))
    closure['external_include_roots'] = sorted(set(closure.get('external_include_roots', [])))


def parse_verilator_messages(text: str) -> Dict:
    """
    Parse Verilator's structured %Warning-CODE / %Error-CODE diagnostics.
    Keep raw text in lint_report as source of truth; this is a convenience index.
    """
    warning_records = []
    error_records = []

    # Examples:
    # %Warning-WIDTHTRUNC: file.sv:272:14: message...
    # %Error-MODNOTFOUND: file.sv:10:1: message...
    pat = re.compile(
        r'(?m)^%(Warning|Error)(?:-([A-Za-z0-9_]+))?:\s*(.*)$'
    )
    for m in pat.finditer(text):
        severity = m.group(1).lower()
        code = m.group(2) or "UNCLASSIFIED"
        message = m.group(3).strip()
        rec = {
            "severity": severity,
            "code": code,
            "message": message,
        }
        if severity == "warning":
            warning_records.append(rec)
        else:
            error_records.append(rec)

    def counts(records):
        out = {}
        for r in records:
            out[r["code"]] = out.get(r["code"], 0) + 1
        return dict(sorted(out.items()))

    return {
        "warning_records": warning_records,
        "error_records": error_records,
        "warning_codes": counts(warning_records),
        "error_codes": counts(error_records),
    }


def run_verilator(top_module: str, filelist: Path, outdir: Path, parameters=None, defines=None) -> Dict:
    exe = shutil.which('verilator')
    report = {
        'tool': 'verilator',
        'tool_path': exe or '',
        'tool_version': verilator_version(),
        'top_module': top_module,
        'filelist': str(filelist),
        'status': 'SKIP_TOOL_MISSING' if not exe else 'NOT_RUN',
        'returncode': None,
        'warning_count': 0,
        'error_count': 0,
        'command': [],
        'stdout': '',
        'stderr': '',
        'warning_codes': {},
        'error_codes': {},
        'warning_records': [],
        'error_records': [],
        'hard_gate': {
            'dependency_closure': 'NOT_EVALUATED',
            'verilator_compile': 'SKIP_TOOL_MISSING' if not exe else 'NOT_RUN',
            'overall': 'NOT_RUN',
        },
    }
    if not exe:
        return report

    cmd = [
        exe,
        '--lint-only',
        '--Wno-fatal',
        '--top-module', top_module,
        '-F', filelist.name,
    ]
    # Project-level preprocessor defines are part of a fixed build context
    # (for example Vortex's XLEN axis).  Keep them separate from -G
    # parameter overrides: -D affects preprocessing of packages/headers,
    # while -G elaborates a top-module parameter.
    for define in (defines or []):
        define = str(define).strip()
        if not define:
            continue
        if define.startswith('-D'):
            define = define[2:]
        cmd.append(f'-D{define}')
    for name, value in (parameters or {}).items():
        cmd += [f'-G{name}={value}']
    p = subprocess.run(cmd, cwd=outdir, text=True, capture_output=True, check=False)
    combined = (p.stdout or '') + '\n' + (p.stderr or '')
    warnings = len(re.findall(r'(?m)^%Warning', combined))
    errors = len(re.findall(r'(?m)^%Error', combined))

    parsed = parse_verilator_messages(combined)
    compile_status = 'PASS' if p.returncode == 0 else 'FAIL'
    report.update({
        'status': compile_status,
        'returncode': p.returncode,
        'warning_count': warnings,
        'error_count': errors,
        'command': cmd,
        'stdout': p.stdout or '',
        'stderr': p.stderr or '',
        'warning_codes': parsed['warning_codes'],
        'error_codes': parsed['error_codes'],
        'warning_records': parsed['warning_records'],
        'error_records': parsed['error_records'],
        'hard_gate': {
            'dependency_closure': 'NOT_EVALUATED',
            'verilator_compile': compile_status,
            'overall': compile_status,
        },
    })
    return report


def main():
    ap = argparse.ArgumentParser(description='Build one recursive RTL candidate closure and optionally run Verilator compile/lint gate')
    ap.add_argument('module', help='Exact top module, e.g. cc_rr_arb_tree')
    ap.add_argument('--project', default='pulp_common_cells')
    ap.add_argument('--sources', default='sources.json')
    ap.add_argument('--workdir', default='work')
    ap.add_argument('--candidate-root', default='candidates')
    ap.add_argument('--candidate-id', default='', help='Optional unique output directory name for batch runs')
    ap.add_argument('--param', action='append', default=[], help='Top parameter override NAME=VALUE; repeatable')
    ap.add_argument('--top-file', default='', help='Disambiguate duplicate module definitions')
    ap.add_argument('--update', action='store_true', help='Update repository before building closure')
    ap.add_argument('--lint', action='store_true', help='Run Verilator --lint-only Hard Gate')
    ap.add_argument(
        '--prune-module',
        action='append',
        default=[],
        help='Configuration-dead module dependency to prune from static closure; repeatable.'
    )
    ap.add_argument(
        '--prune-package',
        action='append',
        default=[],
        help='Configuration-dead package dependency to prune from static closure; repeatable.'
    )
    ap.add_argument(
        '--prune-include',
        action='append',
        default=[],
        help='Configuration-dead include dependency to prune from static closure; repeatable.'
    )
    args = ap.parse_args()

    base = Path.cwd()
    cfg = load_config(base / args.sources)
    candidates = [s for s in cfg.get('sources', []) if s.get('project') == args.project]
    if not candidates:
        raise SystemExit(f'Unknown project in sources config: {args.project}')
    source = candidates[0]

    repo_dir = ensure_repo(source, (base / args.workdir / 'repos').resolve(), update=args.update)
    meta = git_metadata(repo_dir)

    print(f'[model] parsing repository: {args.project}')
    model = RepositoryModel(repo_dir, source)
    print(f'[model] RTL files={len(model.rtl_files)}, modules={sum(len(v) for v in model.module_index.values())}')

    configured_prune_modules = list(source.get('prune_modules', []) or [])
    configured_prune_packages = list(source.get('prune_packages', []) or [])
    configured_prune_includes = list(source.get('prune_includes', []) or [])
    configured_defines = [str(x) for x in (source.get('defines', []) or []) if str(x).strip()]
    closure = build_dependency_closure(
        model,
        args.module,
        args.top_file,
        prune_modules=set(args.prune_module) | set(configured_prune_modules),
        prune_packages=set(args.prune_package) | set(configured_prune_packages),
        prune_includes=set(args.prune_include) | set(configured_prune_includes),
    )

    # Resolve explicitly declared sibling repositories (technology cells,
    # common-cells, vendor assertions, HardFloat, ...).  Dependencies are
    # loaded lazily and only the transitive files selected by the closure are
    # appended to candidate.f.
    dependency_models = {}
    source_by_project = {s.get('project'): s for s in cfg.get('sources', [])}
    pending = list(source.get('dependency_projects', []) or [])
    seen_projects = set()
    while pending:
        project = pending.pop(0)
        if project in seen_projects or project == args.project:
            continue
        dep_source = source_by_project.get(project)
        if not dep_source:
            continue
        seen_projects.add(project)
        dep_repo = ensure_repo(dep_source, (base / args.workdir / 'repos').resolve(), update=args.update)
        dependency_models[project] = RepositoryModel(dep_repo, dep_source)
        pending.extend(dep_source.get('dependency_projects', []) or [])
    if (
        dependency_models
        or source.get('module_overrides')
        or source.get('package_overrides')
        or source.get('include_overrides')
        or configured_prune_modules
        or configured_prune_packages
    ):
        closure = apply_dependency_overlay(
            model,
            closure,
            dependency_models,
            module_overrides=source.get('module_overrides', {}),
            package_overrides=source.get('package_overrides', {}),
            include_overrides=source.get('include_overrides', {}),
            prune_modules=set(args.prune_module) | set(configured_prune_modules),
            prune_packages=set(args.prune_package) | set(configured_prune_packages),
            prune_includes=set(args.prune_include) | set(configured_prune_includes),
        )

    # Include/vendor hints describe roots that are not always discoverable
    # from the lightweight parser (generated headers and legacy macro trees
    # are the common cases). Add primary roots as relative paths and all
    # transitive dependency roots as absolute paths before emitting candidate.f.
    add_declared_include_roots(model, source, closure, primary=True)
    for project, dep_model in dependency_models.items():
        dep_source = source_by_project.get(project, dep_model.source)
        add_declared_include_roots(dep_model, dep_source, closure, primary=False)

    output_name = args.candidate_id or args.module
    outdir = (base / args.candidate_root / safe_name(args.project) / safe_name(output_name)).resolve()
    outdir.mkdir(parents=True, exist_ok=True)

    # Add deterministic project shims (generated headers, black-box memories,
    # or vendor compatibility modules) before writing the candidate filelist.
    materialize_generated_files(source, outdir, closure, base)
    validation_top = materialize_validation_wrapper(source, args.module, outdir, closure)
    wrapper_spec = validation_wrapper_spec(source, args.module)

    # Some legacy Verilog trees keep elaboration-time outputs next to the RTL
    # as ``.v.pyv`` files. The lightweight parser intentionally ignores those
    # generated units; projects may list the small set needed by a candidate
    # here so they are still included deterministically.
    forced_files = []
    # Most forced legacy units are only valid for one top.  A global
    # ``forced_files`` list is retained for backwards compatibility, while
    # ``forced_files_by_module`` prevents unrelated candidates from inheriting
    # an OpenPiton/.v.pyv implementation (and its project-specific headers).
    forced_items = list(source.get('forced_files', []) or [])
    by_module = source.get('forced_files_by_module', {}) or {}
    forced_items.extend(by_module.get(args.module, []) or [])
    forced_items.extend(by_module.get('*', []) or [])
    for item in forced_items:
        rel = str(item).replace('\\\\', '/').lstrip('/')
        path = (repo_dir / rel).resolve()
        repo_root = repo_dir.resolve()
        if path.is_file() and (path == repo_root or repo_root in path.parents):
            forced_files.append(rel)
            if path.suffix.lower() in {'.v', '.sv', '.pyv'}:
                closure.setdefault('module_files', []).append(rel)
            closure.setdefault('include_roots', []).append(str(Path(rel).parent.as_posix()))
    closure['module_files'] = sorted(set(closure.get('module_files', [])))
    closure['include_roots'] = sorted(set(closure.get('include_roots', [])))
    closure['forced_files'] = sorted(set(forced_files))

    # Forced files are real upstream RTL selected by the fixed project
    # configuration (for example CVA6's technology SRAM wrappers).  The
    # lightweight dependency parser may not see them while walking the
    # candidate, so reconcile their module declarations with unresolved
    # submodule edges before computing the hard closure gate.  This keeps the
    # manifest truthful: a dependency is marked resolved only when the actual
    # source file is present in the generated candidate filelist.
    forced_module_files = {}
    for rel in closure['forced_files']:
        src = (repo_dir / rel).resolve()
        if src.suffix.lower() not in {'.v', '.sv'} or not src.is_file():
            continue
        try:
            text = src.read_text(encoding='utf-8', errors='replace')
        except OSError:
            continue
        for name in re.findall(r'(?m)^\s*module\s+([A-Za-z_][A-Za-z0-9_$]*)', text):
            forced_module_files.setdefault(name, rel)
    if forced_module_files:
        for edge in closure.get('unresolved', []):
            name = str(edge.get('dependency_name', ''))
            rel = forced_module_files.get(name)
            if edge.get('dependency_kind') == 'submodule' and rel:
                edge['resolution_status'] = 'resolved_forced_file'
                edge['resolved_file'] = '@forced/' + rel
        closure['unresolved'] = [
            edge for edge in closure.get('unresolved', [])
            if edge.get('resolution_status') not in {
                'resolved', 'resolved_generated', 'resolved_forced_file',
                'pruned_config_dead',
            }
        ]
        closure['closure_status'] = 'COMPLETE' if not closure['unresolved'] else 'PARTIAL'

    filelist = create_filelist(repo_dir, closure, outdir)

    manifest = {
        'schema_version': '0.3',
        'source_project': args.project,
        'repo_url': meta['remote_url'],
        'branch': meta.get('branch', ''),
        'commit_sha': meta['commit_sha'],
        'top_module': closure['top_module'],
        'validation_top': validation_top,
        'validation_wrapper': wrapper_spec or None,
        'fixed_config': source.get('fixed_config'),
        'verification_dependencies': source.get('verification_dependencies', {}),
        'candidate_id': args.candidate_id or args.module,
        'parameter_overrides': {},
        'defines': configured_defines,
        'top_file': closure['top_file'],
        'closure_status': closure['closure_status'],
        'module_files': closure['module_files'],
        'package_files': closure['package_files'],
        'header_files': closure['header_files'],
        'include_roots': closure['include_roots'],
        'external_files': closure.get('external_files', []),
        'external_package_files': closure.get('external_package_files', []),
        'external_include_roots': closure.get('external_include_roots', []),
        'generated_files': closure.get('generated_files', []),
        'generated_header_files': closure.get('generated_header_files', []),
        'forced_files': closure.get('forced_files', []),
        'overlay_projects': closure.get('overlay_projects', []),
        'unresolved_dependencies': closure['unresolved'],
        'parse_warnings': closure['parse_warnings'],
        'pruned_modules': closure.get('pruned_modules', []),
        'pruned_packages': closure.get('pruned_packages', []),
        'pruned_includes': closure.get('pruned_includes', []),
        'candidate_filelist': 'candidate.f',
    }
    (outdir / 'manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

    write_csv(outdir / 'closure_edges.csv', closure['edges'], [
        'parent_kind','parent_name','parent_file','dependency_kind','dependency_name',
        'instance_name','resolution_status','resolved_file'
    ])

    define_flags = ' '.join(f'-D{d[2:] if str(d).startswith("-D") else d}' for d in configured_defines)
    run_script = f'''#!/usr/bin/env bash\nset -euo pipefail\ncd "$(dirname "$0")"\nverilator --lint-only --Wno-fatal --top-module {validation_top} {define_flags} -F candidate.f\n'''
    run_path = outdir / 'run_lint.sh'
    run_path.write_text(run_script, encoding='utf-8')
    run_path.chmod(0o755)

    lint_report = None
    # Start from the fixed project context, then let an explicit CLI value
    # override it for one-off experiments.  Keeping the resolved map in the
    # manifest makes the exact Verilator/Yosys elaboration reproducible.
    parameters = configured_parameter_overrides(source, args.module)
    for item in args.param:
        if '=' not in item:
            raise SystemExit(f'--param expects NAME=VALUE, got {item!r}')
        name, value = item.split('=', 1)
        parameters[name] = value
    manifest['parameter_overrides'] = parameters
    (outdir / 'manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

    if args.lint:
        # In a typed validation wrapper the wrapper owns the concrete DUT
        # parameters; forwarding crawler-inferred parameters to the wrapper
        # itself would address non-existent top-level parameters.
        lint_parameters = parameters if validation_top == args.module else {}
        lint_report = run_verilator(validation_top, filelist, outdir, lint_parameters, configured_defines)
        closure_gate = 'PASS' if closure['closure_status'] == 'COMPLETE' else 'FAIL'
        compile_gate = lint_report['status']
        if compile_gate == 'SKIP_TOOL_MISSING':
            overall_gate = 'SKIP_TOOL_MISSING'
        else:
            overall_gate = 'PASS' if (closure_gate == 'PASS' and compile_gate == 'PASS') else 'FAIL'
        lint_report['hard_gate'] = {
            'dependency_closure': closure_gate,
            'verilator_compile': compile_gate,
            'overall': overall_gate,
        }
        (outdir / 'lint_report.json').write_text(json.dumps(lint_report, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')

        gate_report = {
            'schema_version': '0.3.1',
            'source_project': args.project,
            'commit_sha': meta['commit_sha'],
            'top_module': args.module,
            'validation_top': validation_top,
            'top_file': closure['top_file'],
            'hard_gate': lint_report['hard_gate'],
            'closure_status': closure['closure_status'],
            'unresolved_dependency_count': len(closure['unresolved']),
            'verilator_version': lint_report['tool_version'],
            'verilator_returncode': lint_report['returncode'],
            'warning_count': lint_report['warning_count'],
            'error_count': lint_report['error_count'],
            'warning_codes': lint_report['warning_codes'],
            'error_codes': lint_report['error_codes'],
        }
        (outdir / 'hard_gate_report.json').write_text(
            json.dumps(gate_report, indent=2, ensure_ascii=False) + '\n',
            encoding='utf-8'
        )

    print('\n=== Candidate Build ===')
    print('project          :', args.project)
    print('top_module       :', args.module)
    print('top_file         :', closure['top_file'])
    print('closure_status   :', closure['closure_status'])
    print('module_files     :', len(closure['module_files']))
    print('package_files    :', len(closure['package_files']))
    print('header_files     :', len(closure['header_files']))
    print('include_roots    :', ';'.join(closure['include_roots']) or '(none)')
    print('dependency_edges :', len(closure['edges']))
    print('unresolved       :', len(closure['unresolved']))
    print('pruned_modules   :', ';'.join(closure.get('pruned_modules', [])) or '(none)')
    print('pruned_packages  :', ';'.join(closure.get('pruned_packages', [])) or '(none)')
    print('pruned_includes  :', ';'.join(closure.get('pruned_includes', [])) or '(none)')
    print('candidate_dir    :', outdir)
    print('filelist         :', filelist)
    if lint_report is not None:
        print('\n=== Verilator Hard Gate ===')
        print('tool_version     :', lint_report['tool_version'] or '(not installed)')
        print('status           :', lint_report['status'])
        print('warnings         :', lint_report['warning_count'])
        print('errors           :', lint_report['error_count'])
        print('returncode       :', lint_report['returncode'])
        print('warning_codes    :', json.dumps(lint_report.get('warning_codes', {}), ensure_ascii=False))
        print('overall_gate     :', lint_report.get('hard_gate', {}).get('overall', lint_report['status']))
        print('report           :', outdir / 'lint_report.json')
        print('hard_gate_report :', outdir / 'hard_gate_report.json')


if __name__ == '__main__':
    main()
