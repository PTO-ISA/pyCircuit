def write_csv(path: Path, rows: List[Dict], fields: List[str]):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', newline='', encoding='utf-8') as f:
        w = csv.DictWriter(f, fieldnames=fields, extrasaction='ignore')
        w.writeheader()
        w.writerows(rows)


def safe_name(s: str) -> str:
    return re.sub(r'[^A-Za-z0-9_.-]+', '_', s)


def verilator_version() -> str:
    exe = shutil.which('verilator')
    if not exe:
        return ''
    try:
        p = subprocess.run([exe, '--version'], text=True, capture_output=True, check=False)
        return (p.stdout or p.stderr).strip()
    except Exception:
        return ''


def create_filelist(repo_dir: Path, closure: Dict, outdir: Path) -> Path:
    lines = [
        '// Auto-generated by pyCircuit RTL Crawler v0.3.1.1',
        '// Relative paths in this -F file are relative to this file.',
    ]

    # -F makes relative paths relative to the filelist itself, so use paths from
    # candidate directory to repo files.
    for root in closure['include_roots']:
        inc_abs = (repo_dir / root).resolve()
        rel = Path(shutil.os.path.relpath(inc_abs, outdir.resolve())).as_posix()
        lines.append(f'-I{rel}')

    # Sibling repositories are intentionally kept outside the primary checkout
    # to preserve provenance.  Their include roots are absolute because the
    # candidate filelist can be consumed from either Windows or WSL.
    for root in closure.get('external_include_roots', []):
        lines.append(f'-I{Path(root).resolve().as_posix()}')

    # Packages must appear before modules that import them.
    compile_files = []
    seen = set()
    for relsrc in closure['package_files'] + closure['module_files']:
        if relsrc in seen:
            continue
        seen.add(relsrc)
        compile_files.append(relsrc)

    for relsrc in compile_files:
        src_abs = (repo_dir / relsrc).resolve()
        rel = Path(shutil.os.path.relpath(src_abs, outdir.resolve())).as_posix()
        lines.append(rel)

    # External packages must be read before modules that use their typedefs.
    for src in closure.get('external_package_files', []):
        lines.append(Path(src).resolve().as_posix())
    for src in closure.get('external_files', []):
        lines.append(Path(src).resolve().as_posix())

    path = outdir / 'candidate.f'
    path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return path



def materialize_generated_files(source: Dict, outdir: Path, closure: Dict, config_dir: Path) -> None:
    """Write source-declared generated headers/shims into the candidate."""
    specs = {}
    for rel, content in (source.get('generated_files', {}) or {}).items():
        if isinstance(rel, str) and isinstance(content, str):
            specs[rel.replace('\\\\', '/').lstrip('/')] = content
    for item in (source.get('generated_file_paths', []) or []):
        path = Path(str(item))
        if not path.is_absolute():
            path = config_dir / path
        if path.is_file():
            specs[path.name] = path.read_text(encoding='utf-8')
    if not specs:
        return
    generated_root = (outdir / '_generated').resolve()
    generated_root.mkdir(parents=True, exist_ok=True)
    generated = []
    module_names, include_names = set(), set()
    for rel, content in sorted(specs.items()):
        target = (generated_root / rel).resolve()
        if generated_root not in target.parents and target != generated_root:
            raise ValueError(f'generated file escapes candidate directory: {rel}')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content if content.endswith('\n') else content + '\n', encoding='utf-8')
        generated.append(str(target))
        if target.suffix.lower() in {'.v', '.sv'}:
            module_names.update(re.findall(r'(?m)^\s*module\s+([A-Za-z_][A-Za-z0-9_$]*)', content))
            closure.setdefault('external_files', []).append(str(target))
        else:
            include_names.add(target.name)
            closure.setdefault('external_include_roots', []).append(str(target.parent))
            closure.setdefault('generated_header_files', []).append(str(target))
    for edge in closure.get('unresolved', []):
        name = str(edge.get('dependency_name', ''))
        if edge.get('dependency_kind') == 'submodule' and name in module_names:
            edge['resolution_status'] = 'resolved_generated'
            edge['resolved_file'] = '@generated/' + name
        elif edge.get('dependency_kind') == 'include' and Path(name).name in include_names:
            edge['resolution_status'] = 'resolved_generated'
            edge['resolved_file'] = '@generated/' + Path(name).name
    closure['external_files'] = sorted(set(closure.get('external_files', [])))
    closure['external_include_roots'] = sorted(set(closure.get('external_include_roots', [])))
    closure['generated_files'] = sorted(generated)
    closure['generated_header_files'] = sorted(set(closure.get('generated_header_files', [])))
    closure['unresolved'] = [e for e in closure.get('unresolved', []) if e.get('resolution_status') not in {'resolved', 'resolved_generated', 'pruned_config_dead'}]
    closure['closure_status'] = 'COMPLETE' if not closure['unresolved'] else 'PARTIAL'


def validation_wrapper_spec(source: Dict, module: str) -> Dict:
    specs = source.get('validation_wrappers', {}) or {}
    spec = specs.get(module, {})
    return dict(spec) if isinstance(spec, dict) else {}


def configured_parameter_overrides(source: Dict, module: str) -> Dict:
    """Return deterministic elaboration parameters for one candidate.

    The crawler must not guess values for parameters that change the shape of
    a reusable primitive.  Source manifests may therefore provide exact
    per-module values (and an optional ``*`` fallback).  Values are kept as
    JSON scalars so they can be passed unchanged to both Verilator ``-G`` and
    Yosys ``chparam``.
    """
    raw = source.get('parameter_overrides', {}) or {}
    if not isinstance(raw, dict):
        return {}
    merged = {}
    wildcard = raw.get('*', {})
    if isinstance(wildcard, dict):
        merged.update(wildcard)
    exact = raw.get(module, {})
    if isinstance(exact, dict):
        merged.update(exact)
    return {str(k): v for k, v in merged.items() if str(k).strip()}


